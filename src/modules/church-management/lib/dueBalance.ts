import type { DueType, MemberDue } from '@/modules/church-management/api/fees';
import { isAutoGenerateDueType } from '@/modules/church-management/lib/dueTypes';

/** Church-wide yearly target for a due type (membership rate, etc.). */
export function dueYearTarget(dueType: DueType | undefined): number {
  if (!dueType) return 0;
  return dueType.defaultAmount > 0 ? dueType.defaultAmount : 0;
}

/** Total already paid by this person for a due type in a calendar year. */
export function personYearPaidTotal(
  dues: MemberDue[],
  personId: string,
  dueTypeId: string,
  year: number
): number {
  return dues
    .filter(
      (d) => d.personId === personId && d.dueTypeId === dueTypeId && d.year === year
    )
    .reduce((sum, d) => sum + (Number(d.amountPaid) || 0), 0);
}

/** Remaining balance for the year (target − paid). */
export function personYearRemaining(
  dues: MemberDue[],
  personId: string,
  dueType: DueType | undefined,
  year: number
): number {
  if (!dueType) return 0;
  const target = dueYearTarget(dueType);
  if (target <= 0 && !isAutoGenerateDueType(dueType)) return 0;
  const paid = personYearPaidTotal(dues, personId, dueType.id, year);
  return Math.max(0, Math.round((target - paid) * 100) / 100);
}
