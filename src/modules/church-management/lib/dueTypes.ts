import type { DueType } from '@/modules/church-management/api/fees';

/** Minimal shape for name/code — works with nested dueType on fee rows. */
export type DueTypeLabelSource = {
  code?: string | null;
  name?: string | null;
} | null | undefined;

export function isAutoGenerateDueType(dt: DueType): boolean {
  return dt.autoGenerate === true || dt.code === 'SUBSCRIPTION';
}

/** Person-level remove is only for manual dues — never membership. */
export function canRemovePersonDueAssignment(due: {
  dueType?: DueType | DueTypeLabelSource | null;
}): boolean {
  const dt = due.dueType;
  if (!dt) return true;
  if ('autoGenerate' in dt && typeof (dt as DueType).autoGenerate === 'boolean') {
    return !isAutoGenerateDueType(dt as DueType);
  }
  return (dt.code ?? '').toUpperCase() !== 'SUBSCRIPTION';
}

/** Only membership (auto) uses a shared default. Manual dues: enter amount per member. */
export function shouldPrefillDueAmount(dt: DueType): boolean {
  return isAutoGenerateDueType(dt);
}

export function dueTypeModeLabel(dt: DueType): string {
  if (isAutoGenerateDueType(dt)) {
    return 'Auto (members 18+ only)';
  }
  return 'Manual — all members';
}

/** Billing column label. Membership is yearly; other dues have no schedule. */
export function dueTypeBillingLabel(dt: DueType): string {
  if (isAutoGenerateDueType(dt)) {
    return 'Yearly';
  }
  if (dt.frequency === 'MONTHLY') {
    return 'Monthly';
  }
  if (dt.frequency === 'NONE' || !dt.frequency) {
    return 'When assigned';
  }
  // Legacy YEARLY on manual types — amount is still entered per person.
  return 'When assigned';
}

/**
 * UI label for a due type. Maps legacy typos (Symmetry / Sympathy) → Cemetery Due.
 */
export function dueTypeDisplayName(dt: DueTypeLabelSource, fallback = 'Due'): string {
  if (!dt) return fallback;
  const code = (dt.code ?? '').toUpperCase().trim();
  const name = (dt.name ?? '').trim();
  if (code === 'CEMETERY' || code === 'SYMMETRY' || code === 'SYMPATHY') {
    return 'Cemetery Due';
  }
  if (/symmetr|sympath|cemetr[^e]|cemetry/i.test(name)) {
    return 'Cemetery Due';
  }
  return name || fallback;
}

/** Normalize a free-text due label that may embed a legacy type name. */
export function normalizeDueTypeLabelText(label: string): string {
  return label
    .replace(/\bSymmetr(?:y|ies)\b/gi, 'Cemetery')
    .replace(/\bSympathy\b/gi, 'Cemetery')
    .replace(/\bCemetry\b/gi, 'Cemetery')
    .replace(/\bCemetar(?:y|ies)\b/gi, 'Cemetery');
}
