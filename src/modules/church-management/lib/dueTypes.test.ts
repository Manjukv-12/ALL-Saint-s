import { describe, it, expect } from 'vitest';
import {
  isAutoGenerateDueType,
  shouldPrefillDueAmount,
  dueTypeDisplayName,
  dueTypeBillingLabel,
  canRemovePersonDueAssignment,
} from '@/modules/church-management/lib/dueTypes';
import type { DueType } from '@/modules/church-management/api/fees';

const membership: DueType = {
  id: '1',
  code: 'SUBSCRIPTION',
  name: 'Membership Due',
  defaultAmount: 1000,
  frequency: 'YEARLY',
  isActive: true,
  sortOrder: 1,
  autoGenerate: true,
};

const cemetery: DueType = {
  id: '3',
  code: 'CEMETERY',
  name: 'Cemetery Due',
  defaultAmount: 0,
  frequency: 'NONE',
  isActive: true,
  sortOrder: 3,
};

const buildingFund: DueType = {
  id: '4',
  code: 'BUILDING_FUND',
  name: 'Building fund',
  defaultAmount: 1000,
  frequency: 'NONE',
  isActive: true,
  sortOrder: 4,
  autoGenerate: false,
};

describe('dueTypes — Cemetery Due / membership modes', () => {
  it('treats membership as auto-generate and prefills amount', () => {
    expect(isAutoGenerateDueType(membership)).toBe(true);
    expect(shouldPrefillDueAmount(membership)).toBe(true);
  });

  it('keeps Cemetery Due as manual with no prefilled amount', () => {
    expect(isAutoGenerateDueType(cemetery)).toBe(false);
    expect(shouldPrefillDueAmount(cemetery)).toBe(false);
    expect(cemetery.name).toBe('Cemetery Due');
  });

  it('does not prefill amount for manual types even if a default was stored', () => {
    expect(isAutoGenerateDueType(buildingFund)).toBe(false);
    expect(shouldPrefillDueAmount(buildingFund)).toBe(false);
  });

  it('corrects legacy Symmetry label to Cemetery Due', () => {
    expect(
      dueTypeDisplayName({ ...cemetery, code: 'SYMMETRY', name: 'Symmetry Due' })
    ).toBe('Cemetery Due');
    expect(dueTypeDisplayName({ code: '', name: 'Symmetry' })).toBe('Cemetery Due');
    expect(dueTypeDisplayName({ code: 'HARVEST', name: 'Harvest Due' })).toBe('Harvest Due');
  });

  it('shows Yearly only for membership; manuals are When assigned', () => {
    expect(dueTypeBillingLabel(membership)).toBe('Yearly');
    expect(dueTypeBillingLabel(cemetery)).toBe('When assigned');
    expect(dueTypeBillingLabel(buildingFund)).toBe('When assigned');
    expect(
      dueTypeBillingLabel({ ...cemetery, frequency: 'YEARLY' })
    ).toBe('When assigned');
  });

  it('allows remove only for non-membership person assignments', () => {
    expect(canRemovePersonDueAssignment({ dueType: membership })).toBe(false);
    expect(canRemovePersonDueAssignment({ dueType: cemetery })).toBe(true);
    expect(canRemovePersonDueAssignment({ dueType: buildingFund })).toBe(true);
    expect(canRemovePersonDueAssignment({ dueType: { code: 'SUBSCRIPTION' } })).toBe(false);
  });
});
