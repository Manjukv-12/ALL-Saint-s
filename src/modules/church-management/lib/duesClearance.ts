import type { MemberDue } from '@/modules/church-management/api/fees';
import {
  dueTypeDisplayName,
  isAutoGenerateDueType,
  normalizeDueTypeLabelText,
} from '@/modules/church-management/lib/dueTypes';

export type OutstandingDueItem = {
  id: string;
  label: string;
  year: number;
  remaining: number;
  /** True when membership is one rolled-up line through current month. */
  aggregated?: boolean;
};

export function dueRemaining(due: MemberDue): number {
  return Math.max(0, (Number(due.amountDue) || 0) - (Number(due.amountPaid) || 0));
}

export type ClearanceDueApiItem = {
  dueId: string;
  dueType: string;
  dueCode?: string;
  year: number;
  remaining: number;
  label?: string | null;
  aggregated?: boolean;
};

export function mapClearanceApiItems(items: ClearanceDueApiItem[]): OutstandingDueItem[] {
  return items
    .filter((item) => item.remaining >= 0.001)
    .map((item) => {
      const typeName = dueTypeDisplayName({
        name: item.dueType,
        code: item.dueCode,
      });
      const raw = item.label?.trim() || `${typeName} ${item.year}`;
      return {
        id: item.dueId,
        label: normalizeDueTypeLabelText(raw),
        year: item.year,
        remaining: item.remaining,
        aggregated: !!item.aggregated,
      };
    });
}

/** Client-side fallback when API clearance is missing (legacy backend). */
export function outstandingFromDuesForClearance(dues: MemberDue[]): OutstandingDueItem[] {
  const now = new Date();
  const nowY = now.getFullYear();
  const nowM = now.getMonth() + 1;
  const items: OutstandingDueItem[] = [];

  const membershipRows = dues.filter(
    (d) => d.dueType && isAutoGenerateDueType(d.dueType) && d.month && d.month >= 1 && d.month <= 12
  );

  let membershipTotal = 0;
  if (membershipRows.length > 0) {
    for (const d of membershipRows) {
      const y = d.year;
      const m = Number(d.month) || 0;
      if (y > nowY) continue;
      if (y === nowY && m > nowM) continue;
      membershipTotal += dueRemaining(d);
    }
  } else {
    const yearlyMembership = dues.filter(
      (d) =>
        d.dueType &&
        isAutoGenerateDueType(d.dueType) &&
        (!d.month || d.month < 1) &&
        d.year <= nowY
    );
    membershipTotal = yearlyMembership.reduce((sum, d) => sum + dueRemaining(d), 0);
  }

  if (membershipTotal >= 0.001) {
    const monthLabel = now.toLocaleString('en-IN', { month: 'short', year: 'numeric' });
    items.push({
      id: 'clearance-membership',
      label: `Membership Due (through ${monthLabel})`,
      year: nowY,
      remaining: Math.round(membershipTotal * 100) / 100,
      aggregated: true,
    });
  }

  for (const d of dues) {
    if (d.dueType && isAutoGenerateDueType(d.dueType)) continue;
    if (d.year > nowY) continue;
    const remaining = dueRemaining(d);
    if (remaining < 0.001) continue;
    items.push({
      id: d.id,
      label: `${dueTypeDisplayName(d.dueType)} ${d.year}`,
      year: d.year,
      remaining,
    });
  }

  return items;
}

export function totalClearanceOutstanding(items: OutstandingDueItem[]): number {
  return Math.round(items.reduce((sum, item) => sum + item.remaining, 0) * 100) / 100;
}
