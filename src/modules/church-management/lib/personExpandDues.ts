import type { MemberDue } from '@/modules/church-management/api/fees';
import {
  dueTypeDisplayName,
  isAutoGenerateDueType,
} from '@/modules/church-management/lib/dueTypes';

export type ExpandDueLine = {
  key: string;
  title: string;
  subtitle: string;
  remaining: number;
  /** Prefer this due when paying (oldest unpaid month, yearly, or other). */
  payDue: MemberDue | null;
  sampleDue: MemberDue;
  kind: 'membership' | 'other';
};

function rem(d: MemberDue): number {
  return Math.max(0, Math.round((Number(d.amountDue) || 0) - (Number(d.amountPaid) || 0)));
}

function formatCurrency(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

/**
 * Build a short expand list: one Membership card (year or months rolled up) + each other due.
 * Avoids one card per month in the All-dues dropdown.
 */
export function buildPersonExpandLines(dues: MemberDue[], year: number): ExpandDueLine[] {
  const yearDues = dues.filter((d) => d.year === year);
  const membership = yearDues.filter((d) => d.dueType && isAutoGenerateDueType(d.dueType));
  const other = yearDues.filter((d) => !d.dueType || !isAutoGenerateDueType(d.dueType));

  const lines: ExpandDueLine[] = [];

  const months = membership
    .filter((d) => d.month && d.month >= 1 && d.month <= 12)
    .sort((a, b) => (a.month ?? 0) - (b.month ?? 0));
  const yearly = membership.find((d) => !d.month || d.month < 1);

  if (months.length > 0) {
    const unpaidMonths = months.filter((d) => rem(d) > 0);
    const dueTotal = unpaidMonths.reduce((s, d) => s + Math.round(Number(d.amountDue) || 0), 0);
    const paidTotal = unpaidMonths.reduce((s, d) => s + Math.round(Number(d.amountPaid) || 0), 0);
    const still = unpaidMonths.reduce((s, d) => s + rem(d), 0);
    if (still > 0) {
      lines.push({
        key: `membership-${year}`,
        title: `Membership · ${year}`,
        subtitle:
          unpaidMonths.length === 1
            ? `1 unpaid month · Still ₹${formatCurrency(still)}`
            : `${unpaidMonths.length} unpaid months · Due ₹${formatCurrency(dueTotal)} · Paid ₹${formatCurrency(paidTotal)} · Still ₹${formatCurrency(still)}`,
        remaining: still,
        payDue: unpaidMonths[0] ?? null,
        sampleDue: unpaidMonths[0] ?? months[0],
        kind: 'membership',
      });
    }
  } else if (yearly && rem(yearly) > 0) {
    lines.push({
      key: yearly.id,
      title: `Membership · ${year}`,
      subtitle: `Due ₹${formatCurrency(yearly.amountDue)} · Paid ₹${formatCurrency(yearly.amountPaid)} · Still ₹${formatCurrency(rem(yearly))}`,
      remaining: rem(yearly),
      payDue: yearly,
      sampleDue: yearly,
      kind: 'membership',
    });
  }

  for (const d of other) {
    const still = rem(d);
    if (still < 1 && d.paid) continue;
    if (still < 1 && Math.round(Number(d.amountDue) || 0) < 1) continue;
    lines.push({
      key: d.id,
      title: `${dueTypeDisplayName(d.dueType)} · ${year}`,
      subtitle: `Due ₹${formatCurrency(d.amountDue)} · Paid ₹${formatCurrency(d.amountPaid)}${
        still > 0 ? ` · Still ₹${formatCurrency(still)}` : ''
      }`,
      remaining: still,
      payDue: still > 0 ? d : null,
      sampleDue: d,
      kind: 'other',
    });
  }

  return lines;
}
