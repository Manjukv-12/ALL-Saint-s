import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { Link, useLocation, useNavigate, useParams } from 'react-router-dom';
import { ArrowLeft, IndianRupee } from 'lucide-react';
import { ChurchMgmtPageShell } from '@/modules/church-management/components/ChurchMgmtPageShell';
import { churchMgmtPath } from '@/modules/church-management/paths';
import {
  feesApi,
  type DueType,
  type MemberDue,
  type MembershipFeeStatus,
} from '@/modules/church-management/api/fees';
import { ui } from '@/modules/church-management/components/family-detail/familyDetailTheme';
import { EditDueModal } from '@/modules/church-management/components/fees/EditDueModal';
import { AddPersonDueForm } from '@/modules/church-management/components/fees/AddPersonDueForm';
import { PersonFeesOverview } from '@/modules/church-management/components/fees/PersonFeesOverview';
import { PersonMembershipMonthGrid } from '@/modules/church-management/components/fees/PersonMembershipMonthGrid';
import { PersonOtherDuesList } from '@/modules/church-management/components/fees/PersonOtherDuesList';
import { MembershipPaymentHistoryModal } from '@/modules/church-management/components/fees/MembershipPaymentHistoryModal';
import { membersApi } from '@/modules/church-management/api/families';
import { collectPaymentPath } from '@/modules/church-management/lib/collectPaymentPath';
import { previousDuesPaymentPath } from '@/modules/church-management/lib/previousDuesPayment';
import { isAutoGenerateDueType } from '@/modules/church-management/lib/dueTypes';
import {
  defaultFeesManagementYear,
  feesManagementYearOptions,
} from '@/modules/church-management/lib/feesYearPolicy';
import { FeesYearSplitNotice } from '@/modules/church-management/components/fees/FeesYearSplitNotice';

const yearOptions = feesManagementYearOptions();

function remaining(d: MemberDue): number {
  return Math.max(0, Math.round((Number(d.amountDue) || 0) - (Number(d.amountPaid) || 0)));
}

export default function PersonFeesPage() {
  const { personId = '' } = useParams<{ personId: string }>();
  const navigate = useNavigate();
  const location = useLocation();
  const navState = location.state as
    | {
        personName?: string;
        familyId?: string;
        familyCode?: string;
        payAllClearance?: boolean;
        returnTo?: string;
      }
    | null;
  const [year, setYear] = useState(defaultFeesManagementYear());
  const [dueTypes, setDueTypes] = useState<DueType[]>([]);
  const [dues, setDues] = useState<MemberDue[]>([]);
  const [status, setStatus] = useState<MembershipFeeStatus | null>(null);
  const [personName, setPersonName] = useState(navState?.personName || '');
  const [familyId, setFamilyId] = useState(navState?.familyId || '');
  const [familyCode, setFamilyCode] = useState(navState?.familyCode || '');
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [editDue, setEditDue] = useState<MemberDue | null>(null);
  const [showAdd, setShowAdd] = useState(false);
  const [historyOpen, setHistoryOpen] = useState(false);
  const [refreshKey, setRefreshKey] = useState(0);
  const [converting, setConverting] = useState(false);
  const [convertMsg, setConvertMsg] = useState('');
  const convertAttempted = useRef('');
  const payAllTriggered = useRef(false);

  const feesReturnTo = navState?.returnTo || churchMgmtPath('fees', 'people', personId);

  const openPay = (due: MemberDue, opts?: { prefillAmount?: number; prefillChoice?: string }) => {
    navigate(collectPaymentPath(due), {
      state: {
        due,
        returnTo: feesReturnTo,
        personName: personName || due.personName,
        prefillAmount: opts?.prefillAmount,
        prefillChoice: opts?.prefillChoice,
      },
    });
  };

  const openPayPreviousDues = () => {
    navigate(previousDuesPaymentPath(personId), {
      state: {
        returnTo: feesReturnTo,
        personName,
        familyId,
        familyCode,
      },
    });
  };

  const openMembershipMonths = async () => {
    if (!personId || converting) return;
    try {
      setConverting(true);
      setConvertMsg('');
      convertAttempted.current = '';
      const res = await feesApi.openMembershipMonths(personId, year);
      if (res.error) {
        setConvertMsg(res.error);
        return;
      }
      const hist = await feesApi.getPersonFeeHistory(personId);
      const all = hist.data?.dues ?? [];
      setDues(all);
      const months = all.filter(
        (d) =>
          d.year === year &&
          d.dueType &&
          isAutoGenerateDueType(d.dueType) &&
          d.month &&
          d.month >= 1
      );
      if (months.length < 1) {
        setConvertMsg(
          'Months did not open. Set membership rate / date of birth (18+), then try again — or Apply membership from All dues.'
        );
      } else {
        setConvertMsg(`Month tracker ready · ${months.length} months for ${year}.`);
      }
      const statusRes = await feesApi.getPersonFeeStatus(personId, year);
      if (statusRes.data) setStatus(statusRes.data);
    } catch {
      setConvertMsg('Failed to open month tracker. Try again.');
    } finally {
      setConverting(false);
    }
  };

  const load = useCallback(async () => {
    if (!personId) return;
    try {
      setLoading(true);
      setError('');
      const [typesRes, historyRes, statusRes, memberRes] = await Promise.all([
        feesApi.getDueTypes({ all: true }),
        feesApi.getPersonFeeHistory(personId),
        feesApi.getPersonFeeStatus(personId, year),
        membersApi.getMember(personId),
      ]);
      if (typesRes.data) setDueTypes(typesRes.data);
      const allDues = historyRes.data?.dues ?? [];
      setDues(allDues);
      if (statusRes.data) setStatus(statusRes.data);

      const sample = allDues[0];
      const member = memberRes.data;
      setPersonName(
        member?.fullName ||
          sample?.personName ||
          sample?.person?.fullName ||
          navState?.personName ||
          'Member'
      );
      setFamilyId(member?.familyId || sample?.familyId || navState?.familyId || '');
      setFamilyCode(member?.familyCode || sample?.familyCode || navState?.familyCode || '');
      if (historyRes.error && !allDues.length) setError(historyRes.error);
    } catch {
      setError('Failed to load dues for this person');
    } finally {
      setLoading(false);
    }
  }, [personId, year]);

  useEffect(() => {
    void load();
  }, [load, refreshKey]);

  const yearDues = useMemo(() => dues.filter((d) => d.year === year), [dues, year]);

  const membershipRows = useMemo(
    () =>
      yearDues
        .filter((d) => d.dueType && isAutoGenerateDueType(d.dueType) && d.month)
        .sort((a, b) => (a.month ?? 0) - (b.month ?? 0)),
    [yearDues]
  );

  const yearlyMembership = useMemo(() => {
    return (
      yearDues.find(
        (d) =>
          d.dueType &&
          isAutoGenerateDueType(d.dueType) &&
          !d.month &&
          remaining(d) > 0
      ) ?? null
    );
  }, [yearDues]);

  // Auto-open month rows when only a yearly membership placeholder exists.
  useEffect(() => {
    if (loading || converting || !personId) return;
    if (membershipRows.length > 0 || !yearlyMembership) return;
    const key = `${personId}:${year}:${yearlyMembership.id}`;
    if (convertAttempted.current === key) return;
    convertAttempted.current = key;
    void openMembershipMonths();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading, personId, year, membershipRows.length, yearlyMembership?.id]);

  const otherRows = useMemo(
    () => yearDues.filter((d) => !d.dueType || !isAutoGenerateDueType(d.dueType)),
    [yearDues]
  );

  const otherOutstanding = useMemo(
    () => otherRows.reduce((sum, d) => sum + (d.paid ? 0 : remaining(d)), 0),
    [otherRows]
  );

  const membershipOutstanding = useMemo(() => {
    if (membershipRows.length > 0) {
      const now = new Date();
      const throughMonth =
        year < now.getFullYear() ? 12 : year > now.getFullYear() ? 0 : now.getMonth() + 1;
      return membershipRows.reduce((sum, d) => {
        const m = Number(d.month) || 0;
        if (m < 1 || m > throughMonth) return sum;
        return sum + (d.paid ? 0 : remaining(d));
      }, 0);
    }
    if (yearlyMembership) return remaining(yearlyMembership);
    return Math.round(Number(status?.toCurrentMonthAmount ?? status?.arrearsAmount ?? 0));
  }, [status, membershipRows, yearlyMembership, year]);

  const collected = useMemo(
    () => yearDues.reduce((sum, d) => sum + (Number(d.amountPaid) || 0), 0),
    [yearDues]
  );

  const yearAnnualRate = useMemo(() => {
    const fromMap = Number(status?.yearRates?.[year]);
    if (Number.isFinite(fromMap) && fromMap > 0) return Math.round(fromMap);
    const fromStatus = Number(status?.annualRate);
    if (Number.isFinite(fromStatus) && fromStatus > 0) return Math.round(fromStatus);
    return 0;
  }, [status, year]);

  const yearMonthlyRate = useMemo(() => {
    const fromStatus = Number(status?.monthlyRate);
    if (Number.isFinite(fromStatus) && fromStatus > 0) return Math.round(fromStatus);
    if (yearAnnualRate > 0) return Math.max(1, Math.round(yearAnnualRate / 12));
    return 0;
  }, [status, yearAnnualRate]);

  const payTarget =
    membershipRows.find((d) => remaining(d) > 0) ||
    yearlyMembership ||
    otherRows.find((d) => remaining(d) > 0) ||
    null;

  const toCurrentMonthTotal = useMemo(
    () => Math.round(Number(status?.toCurrentMonthAmount ?? status?.arrearsAmount ?? 0)),
    [status]
  );

  const previousOutstanding = useMemo(() => {
    const prev = status?.previousDues;
    if (!prev?.hasOutstanding || !prev.amount) return 0;
    return Math.round(prev.amount);
  }, [status]);

  const totalDueNow = membershipOutstanding + otherOutstanding + previousOutstanding;

  const openPayAllClearance = () => {
    if (previousOutstanding > 0) {
      openPayPreviousDues();
      return;
    }
    if (!payTarget) return;
    const membershipPrefill = toCurrentMonthTotal > 0 ? toCurrentMonthTotal : membershipOutstanding;
    openPay(payTarget, {
      prefillAmount:
        payTarget.dueType && isAutoGenerateDueType(payTarget.dueType)
          ? membershipPrefill
          : totalDueNow,
      prefillChoice: 'to-current',
    });
  };

  useEffect(() => {
    if (!navState?.payAllClearance || loading || payAllTriggered.current) return;
    if (previousOutstanding <= 0 && (!payTarget || totalDueNow <= 0)) return;
    payAllTriggered.current = true;
    openPayAllClearance();
    // eslint-disable-next-line react-hooks/exhaustive-deps -- run once when dues load for clearance redirect
  }, [
    navState?.payAllClearance,
    loading,
    payTarget?.id,
    toCurrentMonthTotal,
    previousOutstanding,
    totalDueNow,
  ]);

  const subtitle = [
    familyCode ? `Family ${familyCode}` : null,
    status?.paidUntilLabel ? `Paid until ${status.paidUntilLabel}` : null,
  ]
    .filter(Boolean)
    .join(' · ');

  return (
    <ChurchMgmtPageShell
      title={personName ? `Fees — ${personName}` : 'Member fees'}
      subtitle={subtitle || 'Membership and other dues for this person'}
      icon={IndianRupee}
      actions={
        <div className="flex flex-wrap items-center gap-2">
          <Link
            to={churchMgmtPath('fees')}
            className={`${ui.btnOutline} inline-flex items-center gap-1`}
          >
            <ArrowLeft className="h-4 w-4" aria-hidden />
            All dues
          </Link>
          {familyId ? (
            <Link to={churchMgmtPath('families', familyId)} className={ui.btnOutline}>
              Family
            </Link>
          ) : null}
        </div>
      }
    >
      {error ? <p className="text-sm text-red-700">{error}</p> : null}

      {loading ? (
        <p className="p-8 text-center text-slate-500">Loading dues…</p>
      ) : (
        <div className="space-y-5">
          <FeesYearSplitNotice />
          <PersonFeesOverview
            memberName={personName || 'Member'}
            year={year}
            yearOptions={yearOptions}
            status={status}
            membershipOutstanding={membershipOutstanding}
            otherOutstanding={otherOutstanding}
            collected={collected}
            annualRate={yearAnnualRate}
            monthlyRate={yearMonthlyRate}
            onYearChange={setYear}
            onRefresh={() => setRefreshKey((k) => k + 1)}
            onPay={payTarget && totalDueNow < 0.001 ? () => openPay(payTarget) : undefined}
            onPayAll={totalDueNow > 0.001 ? openPayAllClearance : undefined}
            payAllLabel={
              totalDueNow > 0.001
                ? `Pay all due now (₹${totalDueNow.toLocaleString('en-IN')})`
                : undefined
            }
            onPayPreviousDues={
              previousOutstanding > 0 ? openPayPreviousDues : undefined
            }
            onHistory={() => setHistoryOpen(true)}
            onToggleAdd={() => setShowAdd((v) => !v)}
            showAdd={showAdd}
          />

          {showAdd && personId ? (
            <div className={`${ui.card} p-5 sm:p-6`}>
              <h2 className={`${ui.sectionTitle} mb-4`}>Add due</h2>
              <AddPersonDueForm
                dueTypes={dueTypes}
                defaultYear={year}
                defaultPersonId={personId}
                embedded
                onYearChange={setYear}
                onSaved={() => {
                  setShowAdd(false);
                  setRefreshKey((k) => k + 1);
                }}
                onCancel={() => setShowAdd(false)}
              />
            </div>
          ) : null}

          <PersonMembershipMonthGrid
            year={year}
            rows={membershipRows}
            yearlyDue={yearlyMembership}
            monthlyRateHint={yearMonthlyRate}
            annualRateHint={yearAnnualRate}
            converting={converting}
            convertMessage={convertMsg}
            onOpenMonths={() => void openMembershipMonths()}
            onPayMonth={openPay}
            onEditMonth={setEditDue}
            onPayYearly={openPay}
          />

          <PersonOtherDuesList
            year={year}
            rows={otherRows}
            onPay={openPay}
            onEdit={setEditDue}
            onRemoved={() => setRefreshKey((k) => k + 1)}
            onRemoveError={setError}
          />
        </div>
      )}

      <EditDueModal
        due={editDue}
        onClose={() => setEditDue(null)}
        onSaved={() => {
          setEditDue(null);
          setRefreshKey((k) => k + 1);
        }}
      />

      {personId ? (
        <MembershipPaymentHistoryModal
          open={historyOpen}
          personId={personId}
          memberName={personName || 'Member'}
          onClose={() => setHistoryOpen(false)}
        />
      ) : null}
    </ChurchMgmtPageShell>
  );
}
