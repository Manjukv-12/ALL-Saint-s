import { useState } from 'react';
import { History } from 'lucide-react';
import type { DueType, MemberDue } from '@/modules/church-management/api/fees';
import { isAutoGenerateDueType } from '@/modules/church-management/lib/dueTypes';
import { dueRemaining } from '@/modules/church-management/lib/personOutstandingDues';
import { personYearPaidTotal } from '@/modules/church-management/lib/dueBalance';
import { MembershipPaymentHistoryModal } from '@/modules/church-management/components/fees/MembershipPaymentHistoryModal';
import { PersonYearFeeCompletion } from './PersonYearFeeCompletion';
import { ui } from './familyDetailTheme';

function formatCurrency(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

type Props = {
  memberName: string;
  personId: string;
  year: number;
  dues: MemberDue[];
  dueTypes: DueType[];
  onYearChange?: (year: number) => void;
  refreshKey?: string | number;
};

/** Summary cards for one selected member (not family-wide). */
export function MemberDuesSummaryCards({
  memberName,
  personId,
  year,
  dues,
  dueTypes,
  onYearChange,
  refreshKey,
}: Props) {
  const [historyOpen, setHistoryOpen] = useState(false);
  const memberRows = dues.filter((d) => d.personId === personId && d.year === year);
  const collected = memberRows.reduce((sum, d) => sum + (Number(d.amountPaid) || 0), 0);

  const subscription = dueTypes.find((d) => isAutoGenerateDueType(d));
  let outstanding = 0;
  const now = new Date();
  const throughMonth =
    year < now.getFullYear() ? 12 : year > now.getFullYear() ? 0 : now.getMonth() + 1;

  if (subscription) {
    const membershipRows = memberRows.filter(
      (d) => d.dueType && isAutoGenerateDueType(d.dueType) && d.month && d.month >= 1
    );
    if (membershipRows.length > 0) {
      outstanding += membershipRows.reduce((sum, d) => {
        const m = Number(d.month) || 0;
        if (m < 1 || m > throughMonth) return sum;
        return sum + dueRemaining(d);
      }, 0);
    } else if (year <= now.getFullYear()) {
      const paid = personYearPaidTotal(dues, personId, subscription.id, year);
      const target = subscription.defaultAmount > 0 ? subscription.defaultAmount : 0;
      if (target > 0) {
        outstanding += Math.max(0, Math.round((target - paid) * 100) / 100);
      }
    }
  }
  for (const row of memberRows) {
    const code = row.dueType?.code ?? '';
    if (code === 'SUBSCRIPTION') continue;
    if (row.year > now.getFullYear()) continue;
    if (!row.paid) {
      outstanding += dueRemaining(row);
    }
  }

  const membershipPaid = subscription
    ? personYearPaidTotal(dues, personId, subscription.id, year)
    : 0;
  const membershipTarget = subscription?.defaultAmount ?? 0;
  const membershipDone =
    subscription && membershipTarget > 0 ? membershipPaid >= membershipTarget - 0.001 : false;

  const cards = [
    {
      label: 'Collected',
      value: `₹${formatCurrency(collected)}`,
      hint: `${memberRows.filter((d) => (d.amountPaid || 0) > 0).length} payment entr${
        memberRows.filter((d) => (d.amountPaid || 0) > 0).length === 1 ? 'y' : 'ies'
      }`,
    },
    {
      label: 'Outstanding',
      value: `₹${formatCurrency(outstanding)}`,
      hint: outstanding > 0.001 ? 'Due through this month (future months excluded)' : 'Nothing outstanding',
    },
    {
      label: 'Total due',
      value: `₹${formatCurrency(collected + outstanding)}`,
      hint: `Year ${year}`,
    },
    {
      label: 'Membership',
      value: membershipDone ? 'Paid' : outstanding > 0 || membershipTarget > 0 ? 'Open' : '—',
      hint:
        subscription && membershipTarget > 0
          ? `₹${formatCurrency(membershipPaid)} of ₹${formatCurrency(membershipTarget)}`
          : 'No membership rate set',
    },
  ];

  return (
    <div className={ui.card}>
      <div className="flex flex-wrap items-start justify-between gap-3 border-b border-slate-200 px-6 py-5 dark:border-zinc-700">
        <div className="min-w-0">
          <h2 className={ui.sectionTitle}>
            Dues summary — {memberName} ({year})
          </h2>
          <p className="mt-1 text-sm text-slate-500">
            Figures for this member only (not the whole family).
          </p>
        </div>
        <button
          type="button"
          className={`${ui.btnOutline} inline-flex items-center gap-2`}
          onClick={() => setHistoryOpen(true)}
        >
          <History className="h-4 w-4" aria-hidden />
          Payment history
        </button>
      </div>
      <div className="grid gap-px bg-slate-200 sm:grid-cols-2 lg:grid-cols-4 dark:bg-zinc-700">
        {cards.map((item) => (
          <div key={item.label} className="bg-white px-6 py-6 dark:bg-zinc-900">
            <p className="text-sm font-semibold uppercase tracking-wide text-slate-500">
              {item.label}
            </p>
            <p className="mt-2 font-serif text-3xl font-semibold text-slate-900 dark:text-white">
              {item.value}
            </p>
            <p className="mt-1 text-sm text-slate-400">{item.hint}</p>
          </div>
        ))}
      </div>
      {onYearChange ? (
        <PersonYearFeeCompletion
          personId={personId}
          memberName={memberName}
          year={year}
          onYearChange={onYearChange}
          refreshKey={refreshKey}
        />
      ) : null}
      <MembershipPaymentHistoryModal
        open={historyOpen}
        personId={personId}
        memberName={memberName}
        onClose={() => setHistoryOpen(false)}
      />
    </div>
  );
}
