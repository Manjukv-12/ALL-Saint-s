import { useCallback, useEffect, useState } from 'react';
import { useChurchMgmtAuth } from '@/modules/church-management/contexts/ChurchMgmtAuthContext';
import { Pencil, Trash2, Users } from 'lucide-react';
import type { DueType } from '@/modules/church-management/api/fees';
import { feesApi } from '@/modules/church-management/api/fees';
import {
  dueTypeBillingLabel,
  dueTypeDisplayName,
  dueTypeModeLabel,
  isAutoGenerateDueType,
} from '@/modules/church-management/lib/dueTypes';
import { ui } from '@/modules/church-management/lib/churchManagementTheme';
import { ApplyMembershipAfterSaveDialog } from '@/modules/church-management/components/fees/ApplyMembershipAfterSaveDialog';
import { DueTypeAddForm } from '@/modules/church-management/components/fees/DueTypeAddForm';
import { MembershipStepBadge } from '@/modules/church-management/components/fees/MembershipYearSelect';
import {
  clampMembershipYear,
  isValidMembershipYear,
  membershipYearError,
  membershipYearOptions,
} from '@/modules/church-management/lib/membershipYear';
import { AmountNumberInput } from '@/modules/church-management/components/fees/AmountNumberInput';
import { FeesYearSplitNotice } from '@/modules/church-management/components/fees/FeesYearSplitNotice';
import { defaultFeesManagementYear } from '@/modules/church-management/lib/feesYearPolicy';

function formatRupee(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

function isProtectedType(dt: DueType): boolean {
  return isAutoGenerateDueType(dt) || (dt.code || '').toUpperCase() === 'SUBSCRIPTION';
}

type EditMode = 'membership' | 'manual';

export function DueTypesPanel({
  dueTypes,
  onChanged,
  onRateApplied,
  onGoApplyMembership,
}: {
  dueTypes: DueType[];
  onChanged: () => void;
  onRateApplied?: () => void;
  onGoApplyMembership?: () => void;
}) {
  const nowYear = new Date().getFullYear();
  const years = membershipYearOptions(nowYear);

  const [addOpen, setAddOpen] = useState(false);
  const [editId, setEditId] = useState<string | null>(null);
  const [mode, setMode] = useState<EditMode | null>(null);
  const [name, setName] = useState('');
  const [amount, setAmount] = useState('');
  const [year, setYear] = useState(() => clampMembershipYear(defaultFeesManagementYear()));
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [applyPrompt, setApplyPrompt] = useState<{ amount: number; year: number } | null>(null);
  const [lockedYearRates, setLockedYearRates] = useState<Record<number, number>>({});

  const { user } = useChurchMgmtAuth();
  const isSuperAdmin = user?.isSuperAdmin === true;

  const loadLockedYearRates = useCallback(async () => {
    const res = await feesApi.getMembershipYearRates();
    if (res.data?.yearRates) {
      setLockedYearRates(res.data.yearRates);
    }
  }, []);

  useEffect(() => {
    void loadLockedYearRates();
  }, [loadLockedYearRates]);

  const isYearRateLocked = (y: number) => (lockedYearRates[y] ?? 0) > 0;

  const canChangeMembershipForYear = (y: number) => isSuperAdmin || !isYearRateLocked(y);

  const canOpenMembershipEdit =
    isSuperAdmin || years.some((y) => !isYearRateLocked(y));

  const stopEdit = () => {
    setEditId(null);
    setMode(null);
    setError('');
  };

  const beginMembershipEdit = (dt: DueType) => {
    setAddOpen(false);
    setEditId(dt.id);
    setMode('membership');
    const preferred = clampMembershipYear(defaultFeesManagementYear());
    const editYear =
      canChangeMembershipForYear(preferred)
        ? preferred
        : years.find((y) => canChangeMembershipForYear(y)) ?? preferred;
    setYear(editYear);
    const preset = lockedYearRates[editYear] ?? dt.defaultAmount ?? 0;
    setAmount(String(preset));
    setError('');
  };

  const beginManualEdit = (dt: DueType) => {
    setAddOpen(false);
    setEditId(dt.id);
    setMode('manual');
    setName(dueTypeDisplayName(dt));
    setError('');
  };

  const saveMembershipEdit = async (dt: DueType) => {
    const value = Number(amount);
    if (!Number.isFinite(value) || value < 0) {
      setError('Enter a valid amount');
      return;
    }
    if (!isValidMembershipYear(year, nowYear)) {
      setError(membershipYearError(year, nowYear) ?? 'Choose a valid year.');
      return;
    }
    if (!canChangeMembershipForYear(year)) {
      setError('This year’s membership amount is locked. Log in as super admin to change it.');
      return;
    }
    const locked = lockedYearRates[year];
    if (
      locked !== undefined &&
      locked > 0 &&
      Math.abs(locked - value) > 0.001 &&
      !isSuperAdmin
    ) {
      setError('Only super admin can change a membership amount after it is set for this year.');
      return;
    }
    try {
      setBusy(true);
      setError('');
      const res = await feesApi.updateDueType(dt.id, {
        defaultAmount: value,
        year,
        repriceYear: true,
      });
      if (res.error) {
        setError(res.error);
        return;
      }
      stopEdit();
      onChanged();
      await loadLockedYearRates();
      setApplyPrompt({ amount: value, year });
    } catch {
      setError('Could not update membership amount');
    } finally {
      setBusy(false);
    }
  };

  const saveManualEdit = async (dt: DueType) => {
    const trimmed = name.trim();
    if (!trimmed) {
      setError('Name is required');
      return;
    }
    try {
      setBusy(true);
      setError('');
      const res = await feesApi.updateDueType(dt.id, {
        name: trimmed,
        // Manual dues are not yearly/monthly — amount is entered when assigning.
        frequency: 'NONE',
      });
      if (res.error) {
        setError(res.error);
        return;
      }
      stopEdit();
      onChanged();
    } catch {
      setError('Could not update due type');
    } finally {
      setBusy(false);
    }
  };

  const removeType = async (dt: DueType) => {
    if (isProtectedType(dt)) {
      setError('Membership due cannot be deleted.');
      return;
    }
    const label = dueTypeDisplayName(dt);
    if (
      !window.confirm(
        `Remove “${label}” from the active list?\n\nThis does NOT delete dues already assigned to members — those stay on each person.\nYou can Restore this type later under Removed types.`
      )
    ) {
      return;
    }
    try {
      setBusy(true);
      setError('');
      const res = await feesApi.updateDueType(dt.id, { isActive: false });
      if (res.error) {
        setError(res.error);
        return;
      }
      stopEdit();
      onChanged();
    } catch {
      setError('Could not remove due type');
    } finally {
      setBusy(false);
    }
  };

  const restoreType = async (dt: DueType) => {
    try {
      setBusy(true);
      setError('');
      const res = await feesApi.updateDueType(dt.id, { isActive: true });
      if (res.error) {
        setError(res.error);
        return;
      }
      onChanged();
    } catch {
      setError('Could not restore due type');
    } finally {
      setBusy(false);
    }
  };

  const active = dueTypes.filter((d) => d.isActive !== false);
  const inactive = dueTypes.filter((d) => d.isActive === false);

  return (
    <div className="space-y-6">
      <FeesYearSplitNotice />
      <div className={`${ui.card} p-5 sm:p-6`}>
        <p className="m-0 font-sans text-base font-semibold text-slate-900 dark:text-white">
          How this works
        </p>
        <ol className="mt-4 grid gap-4 sm:grid-cols-3">
          <li className="flex gap-3">
            <MembershipStepBadge step={1} />
            <span className="text-sm leading-relaxed text-slate-600 dark:text-zinc-300">
              Set <strong>Membership Due</strong> for a calendar year (shared rate). After a year is
              saved, only the <strong>super admin</strong> login can change that year’s amount.
            </span>
          </li>
          <li className="flex gap-3">
            <MembershipStepBadge step={2} />
            <span className="text-sm leading-relaxed text-slate-600 dark:text-zinc-300">
              Add harvest / cemetery / other types — then <strong>Edit</strong> or{' '}
              <strong>Delete</strong> them here.
            </span>
          </li>
          <li className="flex gap-3">
            <MembershipStepBadge step={3} />
            <span className="text-sm leading-relaxed text-slate-600 dark:text-zinc-300">
              On <strong>All dues</strong>, assign harvest / cemetery / other dues to a person — enter
              year and amount there. Membership stays yearly.
            </span>
          </li>
        </ol>
      </div>

      <div className={ui.card}>
        <div className="flex flex-wrap items-start justify-between gap-4 border-b border-slate-200 px-5 py-5 dark:border-zinc-700 sm:px-6">
          <div className="min-w-0 max-w-2xl">
            <p className="m-0 font-sans text-base font-semibold text-slate-900 dark:text-white">
              Due types
            </p>
            <p className="mt-2 text-sm leading-relaxed text-slate-600 dark:text-zinc-400">
              Membership uses a shared annual amount. Other types have no yearly or monthly schedule —
              enter amounts when you assign a due to a member.
            </p>
          </div>
          <button
            type="button"
            className={ui.btnPrimary}
            onClick={() => {
              stopEdit();
              setAddOpen((v) => !v);
            }}
          >
            {addOpen ? 'Cancel' : 'Add due type'}
          </button>
        </div>

        {error ? <div className={`mx-5 mt-4 sm:mx-6 ${ui.alertError}`}>{error}</div> : null}

        {addOpen ? (
          <DueTypeAddForm
            onCancel={() => setAddOpen(false)}
            onSaved={() => {
              setAddOpen(false);
              onChanged();
            }}
            onError={setError}
          />
        ) : null}

        <div className={ui.tableScroll}>
          <table className={ui.tableMin}>
            <thead className={ui.tableHead}>
              <tr>
                <th className={ui.th}>Name</th>
                <th className={ui.th}>How added</th>
                <th className={ui.th}>Billing</th>
                <th className={ui.th}>Amount</th>
                <th className={`${ui.th} text-right`}>Actions</th>
              </tr>
            </thead>
            <tbody>
              {active.map((dt) => {
                const membership = isAutoGenerateDueType(dt);
                const label = dueTypeDisplayName(dt);
                const editing = editId === dt.id;

                return (
                  <tr key={dt.id} className={ui.row}>
                    <td className={ui.td}>
                      {editing && mode === 'manual' ? (
                        <input
                          value={name}
                          onChange={(e) => setName(e.target.value)}
                          className={`${ui.input} min-w-[10rem]`}
                          aria-label="Due type name"
                        />
                      ) : (
                        <span className="font-medium">{label}</span>
                      )}
                      <p className="mt-0.5 text-xs text-slate-500">{dt.code}</p>
                    </td>
                    <td className={ui.td}>
                      <span className="text-sm text-slate-600 dark:text-zinc-400">
                        {dueTypeModeLabel(dt)}
                      </span>
                    </td>
                    <td className={ui.td}>
                      <span className="text-sm text-slate-600 dark:text-zinc-400">
                        {dueTypeBillingLabel(dt)}
                      </span>
                    </td>
                    <td className={ui.td}>
                      {membership ? (
                        editing && mode === 'membership' ? (
                          <div className="space-y-2">
                            <div className="flex flex-wrap items-center gap-2">
                              <select
                                value={year}
                                onChange={(e) => {
                                  const y = Number(e.target.value);
                                  setYear(y);
                                  const locked = lockedYearRates[y];
                                  if (locked !== undefined && locked > 0) {
                                    setAmount(String(locked));
                                  }
                                }}
                                className={`${ui.select} w-28`}
                                aria-label="Membership year"
                              >
                                {years.map((y) => (
                                  <option key={y} value={y} disabled={!canChangeMembershipForYear(y)}>
                                    {y}
                                    {isYearRateLocked(y) && !isSuperAdmin ? ' (locked)' : ''}
                                  </option>
                                ))}
                              </select>
                              <span className="text-sm text-slate-500">₹</span>
                              <AmountNumberInput
                                min={0}
                                value={amount}
                                onChange={(e) => setAmount(e.target.value)}
                                className={`${ui.input} w-28`}
                                aria-label={`Membership amount for ${year}`}
                                disabled={!canChangeMembershipForYear(year)}
                              />
                            </div>
                            {!canChangeMembershipForYear(year) ? (
                              <p className="text-xs text-amber-700 dark:text-amber-300">
                                Locked for {year}. Use the super admin account to edit.
                              </p>
                            ) : null}
                          </div>
                        ) : (
                          <div>
                            <span className="font-medium tabular-nums">
                              ₹{formatRupee(dt.defaultAmount)}
                            </span>
                            <p className="mt-0.5 text-xs text-slate-500">Annual · per calendar year</p>
                          </div>
                        )
                      ) : (
                        <span className="text-sm text-slate-500">Per member when assigned</span>
                      )}
                    </td>
                    <td className={`${ui.td} text-right`}>
                      {membership ? (
                        editing && mode === 'membership' ? (
                          <div className="inline-flex flex-wrap justify-end gap-2">
                            <button
                              type="button"
                              disabled={busy || !canChangeMembershipForYear(year)}
                              className={ui.btnPrimary}
                              onClick={() => void saveMembershipEdit(dt)}
                            >
                              {busy ? 'Saving…' : `Save for ${year}`}
                            </button>
                            <button type="button" className={ui.btnOutline} onClick={stopEdit}>
                              Cancel
                            </button>
                          </div>
                        ) : canOpenMembershipEdit ? (
                          <button
                            type="button"
                            className={ui.btnGhost}
                            onClick={() => beginMembershipEdit(dt)}
                          >
                            {isSuperAdmin ? 'Edit amount & year' : 'Set amount for a year'}
                          </button>
                        ) : (
                          <span className="text-xs text-slate-500">
                            Locked — super admin only
                          </span>
                        )
                      ) : editing && mode === 'manual' ? (
                        <div className="inline-flex flex-wrap justify-end gap-2">
                          <button
                            type="button"
                            disabled={busy}
                            className={ui.btnPrimary}
                            onClick={() => void saveManualEdit(dt)}
                          >
                            {busy ? 'Saving…' : 'Save'}
                          </button>
                          <button type="button" className={ui.btnOutline} onClick={stopEdit}>
                            Cancel
                          </button>
                        </div>
                      ) : (
                        <div className="inline-flex flex-wrap justify-end gap-1">
                          <button
                            type="button"
                            className={`${ui.btnGhost} inline-flex items-center gap-1`}
                            onClick={() => beginManualEdit(dt)}
                            title="Edit name"
                          >
                            <Pencil className="h-3.5 w-3.5" aria-hidden />
                            Edit
                          </button>
                          <button
                            type="button"
                            disabled={busy}
                            className={`${ui.btnGhost} inline-flex items-center gap-1 text-red-700 hover:bg-red-50 dark:text-red-300`}
                            onClick={() => void removeType(dt)}
                            title="Remove from active list"
                          >
                            <Trash2 className="h-3.5 w-3.5" aria-hidden />
                            Delete
                          </button>
                        </div>
                      )}
                    </td>
                  </tr>
                );
              })}
              {active.length === 0 ? (
                <tr>
                  <td colSpan={5} className={`${ui.td} text-center text-slate-500`}>
                    No active due types. Add one to get started.
                  </td>
                </tr>
              ) : null}
            </tbody>
          </table>
        </div>

        {inactive.length > 0 ? (
          <div className="border-t border-slate-200 px-5 py-4 dark:border-zinc-700 sm:px-6">
            <p className="text-sm font-semibold text-slate-700 dark:text-zinc-300">Removed types</p>
            <p className="mt-1 text-xs text-slate-500">
              Hidden from new assignments only. Fees already on members are unchanged.
            </p>
            <ul className="mt-2 space-y-2">
              {inactive.map((dt) => (
                <li
                  key={dt.id}
                  className="flex flex-wrap items-center justify-between gap-2 text-sm text-slate-600 dark:text-zinc-400"
                >
                  <span>
                    {dueTypeDisplayName(dt)}{' '}
                    <span className="text-xs text-slate-400">({dt.code})</span>
                  </span>
                  <button
                    type="button"
                    disabled={busy}
                    className={ui.btnGhost}
                    onClick={() => void restoreType(dt)}
                  >
                    Restore
                  </button>
                </li>
              ))}
            </ul>
          </div>
        ) : null}
      </div>

      {onGoApplyMembership ? (
        <div className={`${ui.card} flex flex-wrap items-center justify-between gap-4 px-5 py-5 sm:px-6`}>
          <div>
            <p className="font-semibold text-slate-900 dark:text-white">Apply membership</p>
            <p className="mt-1 text-sm text-slate-600 dark:text-zinc-400">
              After you set the annual rate for a year, apply it on the Membership tab.
            </p>
          </div>
          <button
            type="button"
            className={`${ui.btnPrimary} inline-flex items-center gap-2`}
            onClick={onGoApplyMembership}
          >
            <Users className="h-4 w-4" aria-hidden />
            Open Membership
          </button>
        </div>
      ) : null}

      <ApplyMembershipAfterSaveDialog
        open={applyPrompt !== null}
        amount={applyPrompt?.amount ?? 0}
        initialYear={applyPrompt?.year}
        onClose={() => setApplyPrompt(null)}
        onApplied={() => {
          onChanged();
          onRateApplied?.();
          onGoApplyMembership?.();
        }}
      />
    </div>
  );
}
