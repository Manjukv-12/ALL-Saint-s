import { useEffect, useMemo, useState } from 'react';
import { History } from 'lucide-react';
import { Link } from 'react-router-dom';
import type { Member } from '@/modules/church-management/api/types';
import {
  feesApi,
  MembershipFeeState,
  type DueType,
  type MemberDue,
  type MembershipFeeStatus,
} from '@/modules/church-management/api/fees';
import { personsApi } from '@/modules/church-management/api/persons';
import {
  dueTypeDisplayName,
  isAutoGenerateDueType,
} from '@/modules/church-management/lib/dueTypes';
import { personYearRemaining } from '@/modules/church-management/lib/dueBalance';
import { isEligibleForMembershipFee } from '@/modules/church-management/lib/membershipEligibility';
import { isActiveMemberStatus } from '@/modules/church-management/lib/membershipType';
import { ui } from '@/modules/church-management/components/family-detail/familyDetailTheme';
import { MemberSearchSelect } from './MemberSearchSelect';
import { ConfirmDueAmountDialog } from './ConfirmDueAmountDialog';
import {
  AssignDuePaymentSection,
  type AssignPaymentMode,
} from './AssignDuePaymentSection';
import { MembershipPaymentHistoryModal } from '@/modules/church-management/components/fees/MembershipPaymentHistoryModal';
import {
  MembershipPaymentGuide,
  membershipPaymentPlainSummary,
  type MembershipPayChoice,
} from '@/modules/church-management/components/fees/MembershipPaymentGuide';
import {
  checkDueAmount,
  checkWholeMonthPayment,
  membershipMonthlyRate,
  membershipRoundPayUnit,
} from '@/modules/church-management/lib/dueAmountValidation';
import { AmountNumberInput } from './AmountNumberInput';
import {
  membershipAmountForMonths,
  previewMembershipCoverage,
} from '@/modules/church-management/lib/membershipCoverage';
import { DatePartsField } from '@/components/DatePartsField';
import { FEES_SYSTEM_START_YEAR } from '@/modules/church-management/lib/feesYearPolicy';

type Props = {
  dueTypes: DueType[];
  defaultYear: number;
  members?: Member[];
  existingDues?: MemberDue[];
  churchWide?: boolean;
  defaultPersonId?: string;
  /** When true, require member first — detail fields stay hidden until selected. */
  memberFirst?: boolean;
  embedded?: boolean;
  inModal?: boolean;
  /** Optional link to the full person fee details page (shown after member select). */
  feeDetailsHref?: string;
  feeDetailsState?: Record<string, unknown>;
  onSaved: () => void;
  onCancel?: () => void;
  onPersonChange?: (personId: string, member: Member | null) => void;
  /** Keep listing/summary year in sync when the form year changes. */
  onYearChange?: (year: number) => void;
};

export function AddPersonDueForm({
  dueTypes: dueTypesProp,
  defaultYear,
  members: fixedMembers,
  existingDues = [],
  churchWide = false,
  defaultPersonId,
  memberFirst = false,
  embedded = false,
  inModal = false,
  feeDetailsHref,
  feeDetailsState,
  onSaved,
  onCancel,
  onPersonChange,
  onYearChange,
}: Props) {
  /** Membership is applied church-wide — Add due is only for personal dues. */
  const dueTypes = useMemo(
    () => dueTypesProp.filter((dt) => !isAutoGenerateDueType(dt)),
    [dueTypesProp]
  );

  const [personId, setPersonId] = useState(defaultPersonId || '');
  const [dueTypeId, setDueTypeId] = useState('');
  const [year, setYear] = useState(defaultYear);
  const [month, setMonth] = useState('');
  const [amountDue, setAmountDue] = useState('');
  const [amountPaid, setAmountPaid] = useState('');
  const [paidDate, setPaidDate] = useState('');
  const [paymentMode, setPaymentMode] = useState<AssignPaymentMode>('unpaid');
  const [assignedDate, setAssignedDate] = useState(() => new Date().toISOString().slice(0, 10));
  const [comments, setComments] = useState('');
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState('');
  const [successNote, setSuccessNote] = useState('');
  const [memberSearch, setMemberSearch] = useState('');
  const [churchMembers, setChurchMembers] = useState<Member[]>([]);
  const [loadingMembers, setLoadingMembers] = useState(false);
  const [pickedMember, setPickedMember] = useState<Member | null>(null);
  const [confirmOpen, setConfirmOpen] = useState(false);
  const [membershipStatus, setMembershipStatus] = useState<MembershipFeeStatus | null>(null);
  const [loadingMembershipStatus, setLoadingMembershipStatus] = useState(false);
  const [historyOpen, setHistoryOpen] = useState(false);

  const memberOptions = useMemo(() => {
    const list = churchWide ? churchMembers : (fixedMembers ?? []);
    // Keep Married Away / Deceased selectable so paid history can be viewed.
    return list.filter(
      (m) =>
        isActiveMemberStatus(m) || m.status === 'Separated' || m.status === 'Deceased'
    );
  }, [churchWide, churchMembers, fixedMembers]);

  const selectedType = dueTypes.find((d) => d.id === dueTypeId);
  const selectedMember =
    pickedMember?.id === personId
      ? pickedMember
      : memberOptions.find((m) => m.id === personId) ?? null;
  const historyOnlyMember =
    !!selectedMember &&
    (selectedMember.status === 'Separated' || selectedMember.status === 'Deceased');
  const isSubscription = !!selectedType && isAutoGenerateDueType(selectedType);
  const membershipEligibleBlocked =
    isSubscription &&
    !!selectedMember &&
    !isEligibleForMembershipFee(selectedMember.dateOfBirth);

  const remainingFromList = useMemo(() => {
    if (!personId || !selectedType || !isAutoGenerateDueType(selectedType)) return null;
    if (existingDues.length === 0) return null;
    return personYearRemaining(existingDues, personId, selectedType, year);
  }, [existingDues, personId, selectedType, year]);

  // Monthly membership allows advance payments even when current months are covered.
  const membershipBlocked = membershipEligibleBlocked;
  const monthlyRate = useMemo(() => {
    if (!isSubscription || !selectedType) return 0;
    const fromStatus = Number(membershipStatus?.monthlyRate);
    if (Number.isFinite(fromStatus) && fromStatus > 0) return fromStatus;
    const annual =
      Number(membershipStatus?.annualRate) ||
      Number(selectedMember?.membershipFeeAmount) ||
      Number(selectedType.defaultAmount) ||
      0;
    return membershipMonthlyRate(annual);
  }, [isSubscription, selectedType, membershipStatus, selectedMember]);

  const roundPayUnit = useMemo(() => {
    const fromStatus = Number(membershipStatus?.roundPayUnit);
    if (Number.isFinite(fromStatus) && fromStatus > 0) return fromStatus;
    return membershipRoundPayUnit(monthlyRate);
  }, [membershipStatus?.roundPayUnit, monthlyRate]);

  const membershipCoverage = useMemo(() => {
    if (!isSubscription || monthlyRate < 1) return null;
    const amt = Number(amountDue) || 0;
    const next = membershipStatus?.nextDueMonth;
    const startYear = next?.year ?? year;
    const startMonth = next?.month ?? 1;
    const finishNext = Number(next?.remaining);
    const annual =
      Number(membershipStatus?.annualRate) ||
      Number(selectedType?.defaultAmount) ||
      monthlyRate * 12;
    return previewMembershipCoverage({
      amountPaid: amt,
      startYear,
      startMonth,
      startMonthRemaining:
        Number.isFinite(finishNext) && finishNext > 0 && finishNext < monthlyRate
          ? finishNext
          : undefined,
      fallbackAnnual: annual,
      yearRates: membershipStatus?.yearRates ?? null,
    });
  }, [
    isSubscription,
    monthlyRate,
    amountDue,
    membershipStatus,
    year,
    selectedType?.defaultAmount,
  ]);

  const remaining = useMemo(() => {
    if (!isSubscription || !personId) return null;
    const arrears = Number(membershipStatus?.arrearsAmount);
    if (Number.isFinite(arrears) && arrears > 0) return arrears;
    if (membershipStatus?.state === MembershipFeeState.UNPAID) {
      const fromStatus = Number(membershipStatus.amountDue);
      if (Number.isFinite(fromStatus) && fromStatus >= 0) return fromStatus;
    }
    if (remainingFromList != null && remainingFromList > 0) return remainingFromList;
    if (monthlyRate > 0) return monthlyRate;
    return null;
  }, [
    isSubscription,
    personId,
    remainingFromList,
    membershipStatus,
    monthlyRate,
  ]);

  const showDetails = !memberFirst || !!personId;

  useEffect(() => {
    setYear(defaultYear);
  }, [defaultYear]);

  useEffect(() => {
    if (!isSubscription || !personId) {
      setMembershipStatus(null);
      return;
    }
    let cancelled = false;
    const load = async () => {
      setLoadingMembershipStatus(true);
      const res = await feesApi.getPersonFeeStatus(personId, year);
      if (!cancelled) {
        setMembershipStatus(res.data ?? null);
        setLoadingMembershipStatus(false);
      }
    };
    void load();
    return () => {
      cancelled = true;
    };
  }, [isSubscription, personId, year]);

  useEffect(() => {
    if (!churchWide) return;
    const q = memberSearch.trim();
    if (!q) {
      setChurchMembers([]);
      setLoadingMembers(false);
      setError('');
      return;
    }
    let cancelled = false;
    const load = async () => {
      setLoadingMembers(true);
      // Use persons search (name / phone / family code) — do not pass members
      // status=Active; that filters computed membershipStatus and hides
      // family-split heads labeled "Moved To" who are still Active persons.
      const res = await personsApi.searchPersons(q, 40);
      if (cancelled) return;
      if (res.data) {
        setChurchMembers(Array.isArray(res.data) ? res.data : []);
        setError('');
      } else {
        setChurchMembers([]);
        setError(res.error || 'Could not search members. Try again.');
      }
      setLoadingMembers(false);
    };
    void load();
    return () => {
      cancelled = true;
    };
  }, [churchWide, memberSearch]);

  useEffect(() => {
    if (dueTypes.length === 0) return;
    setDueTypeId((prev) => prev || dueTypes[0].id);
  }, [dueTypes]);

  useEffect(() => {
    if (defaultPersonId) setPersonId(defaultPersonId);
  }, [defaultPersonId]);

  // Membership: default to one usual month collection (simple).
  useEffect(() => {
    if (!selectedType) return;

    if (isAutoGenerateDueType(selectedType)) {
      if (monthlyRate > 0) {
        const finishNext = Number(membershipStatus?.nextDueMonth?.remaining);
        const three = membershipAmountForMonths(
          monthlyRate,
          3,
          Number.isFinite(finishNext) && finishNext > 0 && finishNext < monthlyRate
            ? finishNext
            : undefined
        );
        if (
          Number.isFinite(finishNext) &&
          finishNext > 0 &&
          finishNext < monthlyRate
        ) {
          setAmountDue(String(finishNext));
        } else if (three > 0) {
          setAmountDue(String(three));
        } else if (roundPayUnit > 0) {
          setAmountDue(String(roundPayUnit));
        } else {
          setAmountDue(String(monthlyRate));
        }
      } else {
        setAmountDue('');
      }
      return;
    }

    setAmountDue('');
  }, [
    selectedType?.id,
    selectedType?.defaultAmount,
    personId,
    year,
    monthlyRate,
    roundPayUnit,
    membershipStatus?.nextDueMonth?.remaining,
  ]);

  const expectedAmount =
    selectedType && isAutoGenerateDueType(selectedType)
      ? monthlyRate > 0
        ? monthlyRate
        : selectedType.defaultAmount
      : null;

  const amountCheck = useMemo(() => {
    if (amountDue === '' || expectedAmount == null) {
      return { needsReentry: false, warnings: [] as string[] };
    }
    if (isSubscription && monthlyRate > 0) {
      const paid = amountPaid === '' ? Number(amountDue) || 0 : Number(amountPaid) || 0;
      const checkAmt = amountPaid !== '' ? paid : Number(amountDue) || 0;
      return checkWholeMonthPayment(checkAmt, monthlyRate);
    }
    return checkDueAmount(Number(amountDue) || 0, expectedAmount);
  }, [amountDue, amountPaid, expectedAmount, isSubscription, monthlyRate]);

  const selectPerson = (id: string, member?: Member) => {
    setPersonId(id);
    setPickedMember(member ?? null);
    setSuccessNote('');
    onPersonChange?.(id, member ?? null);
  };

  const finishSaved = (note?: string) => {
    setConfirmOpen(false);
    onSaved();
    // Modal / dismissible form: close immediately — no extra Done click.
    if (onCancel) {
      onCancel();
      return;
    }
    if (note) {
      setSuccessNote(note);
    }
  };

  const saveDue = async () => {
    try {
      setSaving(true);
      setError('');
      if (historyOnlyMember) {
        setError(
          selectedMember?.status === 'Separated'
            ? 'Cannot add new dues for Married Away members. Their paid entries stay in the list below.'
            : 'Cannot add new dues for Deceased members. Their paid entries stay in the list below.'
        );
        setConfirmOpen(false);
        return;
      }
      const feeAmount = Number(amountDue);
      const paid =
        !isSubscription && paymentMode === 'unpaid'
          ? 0
          : amountPaid === ''
            ? 0
            : Number(amountPaid);

      if (isSubscription) {
        if (!selectedMember || !isEligibleForMembershipFee(selectedMember.dateOfBirth)) {
          setError('Membership due applies to members aged 18+ with date of birth on file');
          setConfirmOpen(false);
          return;
        }
        // Amount due field is the payment for membership (whole months).
        const payAmount = paid > 0 ? paid : feeAmount;
        if (monthlyRate > 0) {
          const whole = checkWholeMonthPayment(payAmount, monthlyRate);
          if (whole.needsReentry) {
            setError(whole.warnings[0] || 'Enter a valid membership amount');
            setConfirmOpen(false);
            return;
          }
        }
        if (payAmount > 0 && !paidDate) {
          setError('Enter the payment date when a paid amount is recorded');
          setConfirmOpen(false);
          return;
        }

        const res = await feesApi.createOrUpdateDue({
          personId,
          dueTypeId,
          year,
          amountDue: payAmount,
          amountPaid: payAmount,
          paidDate: paidDate || new Date().toISOString().slice(0, 10),
          comments: comments.trim() || undefined,
          newEntry: true,
        });
        if (res.error) {
          setError(res.error);
          setConfirmOpen(false);
          return;
        }

        setComments('');
        setMonth('');
        setAmountPaid('');
        setPaidDate('');
        finishSaved();
        return;
      }

      if (paid > 0 && !paidDate) {
        setError('Enter the payment date when a paid amount is recorded');
        setConfirmOpen(false);
        return;
      }

      const assigned = assignedDate.trim();
      const noteParts = [
        assigned ? `Assigned ${assigned}` : '',
        comments.trim(),
      ].filter(Boolean);
      const res = await feesApi.createOrUpdateDue({
        personId,
        dueTypeId,
        year,
        amountDue: feeAmount,
        amountPaid: paid,
        paidDate: paid > 0 ? paidDate : undefined,
        month: month ? Number(month) : undefined,
        comments: noteParts.length ? noteParts.join(' · ') : undefined,
        newEntry: true,
      });
      if (res.error) {
        setError(res.error);
        setConfirmOpen(false);
        return;
      }

      const savedTypeId = dueTypeId;
      const savedTypeName = selectedType ? dueTypeDisplayName(selectedType) : 'Due';
      const nextType =
        dueTypes.find((dt) => dt.id !== savedTypeId) ?? dueTypes[0] ?? null;
      setComments('');
      setMonth('');
      setAmountPaid('');
      setPaidDate('');
      setPaymentMode('unpaid');
      setAmountDue('');
      setDueTypeId(nextType?.id || '');
      finishSaved(
        `${savedTypeName} for ${year} saved (assigned ${assigned || 'today'}). Member and year kept — pick another due type if needed.`
      );
    } catch {
      setError('Could not add due');
      setConfirmOpen(false);
    } finally {
      setSaving(false);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!personId || !dueTypeId) {
      setError('Select a member and due type');
      return;
    }
    if (year < FEES_SYSTEM_START_YEAR) {
      setError(
        `Assign dues from ${FEES_SYSTEM_START_YEAR} onward only. Record earlier balances on the member profile.`
      );
      return;
    }
    if (Number(amountDue) <= 0 || amountDue === '') {
      setError('Enter a valid amount due greater than zero');
      return;
    }
    if (!isSubscription && paymentMode === 'record') {
      if (amountPaid === '' || Number(amountPaid) <= 0) {
        setError('Enter the paid amount to clear this payment, or choose Unpaid');
        return;
      }
      if (!paidDate) {
        setError('Enter the payment date when clearing payment');
        return;
      }
    }
    if (amountPaid !== '' && Number(amountPaid) < 0) {
      setError('Paid amount cannot be negative');
      return;
    }
    if (Number(amountPaid) > 0 && !paidDate) {
      setError('Enter the payment date for the paid amount');
      return;
    }
    if (isSubscription && monthlyRate > 0) {
      const payAmount =
        amountPaid !== '' && Number(amountPaid) > 0 ? Number(amountPaid) : Number(amountDue) || 0;
      const whole = checkWholeMonthPayment(payAmount, monthlyRate);
      if (whole.needsReentry) {
        setError(whole.warnings[0] || 'Enter a valid membership amount');
        return;
      }
      if (!paidDate) {
        setError('Enter the payment date for the membership payment');
        return;
      }
    }
    if (membershipEligibleBlocked) {
      setError('Membership due applies to members aged 18+ with date of birth on file');
      return;
    }
    setError('');
    // Only confirm when amount needs re-check; otherwise save and close.
    if (amountCheck.needsReentry) {
      setConfirmOpen(true);
      return;
    }
    void saveDue();
  };

  const monthLabel =
    month && selectedType?.frequency === 'MONTHLY'
      ? new Date(2000, Number(month) - 1, 1).toLocaleString('en-IN', { month: 'long' })
      : undefined;

  const showHeader = !inModal && !embedded;
  const shellClass = embedded || inModal ? '' : ui.card;
  const labelClass = 'text-base font-semibold text-slate-700 dark:text-zinc-300';
  const inputClass = `${ui.input} mt-2 w-full text-lg leading-normal py-4 min-h-[3.25rem]`;

  return (
    <div className={shellClass}>
      {showHeader && (
        <div className={ui.sectionHead}>
          <h2 className={ui.sectionTitle}>Add due for a person</h2>
          <p className="mt-1 text-sm text-slate-500">
            Assign harvest, cemetery, or other yearly dues to one member for a calendar year. After
            saving, you can add another type for the same person and year. Membership is applied
            separately for all eligible members.
          </p>
        </div>
      )}

      <form
        onSubmit={handleSubmit}
        className={embedded || inModal ? 'space-y-6' : ui.sectionBody}
      >
        {error && (
          <div className="rounded-lg border border-red-200 bg-red-50 p-3 text-sm text-red-700">
            {error}
          </div>
        )}

        {successNote && (
          <div className="rounded-lg border border-emerald-200 bg-emerald-50 p-3 text-sm text-emerald-900 dark:border-emerald-800 dark:bg-emerald-950/30 dark:text-emerald-100">
            {successNote}
          </div>
        )}

        {dueTypes.length === 0 ? (
          <p className="text-base text-slate-600">
            No personal due types configured. Add harvest, cemetery, or other types under Due types.
            Membership is applied with <strong>Apply membership</strong>, not here.
          </p>
        ) : (
          <div className="space-y-6">
            <MemberSearchSelect
              value={personId}
              onChange={selectPerson}
              members={memberOptions}
              selectedMember={selectedMember}
              loading={churchWide && loadingMembers}
              onSearchChange={churchWide ? setMemberSearch : undefined}
            />

            {personId && selectedMember && feeDetailsHref ? (
              <div className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-slate-200 bg-slate-50 px-4 py-3 dark:border-zinc-700 dark:bg-zinc-800/50">
                <p className="text-sm text-slate-700 dark:text-zinc-200">
                  Selected <strong>{selectedMember.fullName}</strong> — view their membership months,
                  outstanding dues, and payment history.
                </p>
                <Link
                  to={feeDetailsHref}
                  state={feeDetailsState}
                  className={`${ui.btnOutline} shrink-0 bg-white dark:bg-zinc-900`}
                >
                  Fee details
                </Link>
              </div>
            ) : null}

            {!showDetails && (
              <p className="rounded-lg border border-dashed border-slate-200 bg-slate-50 px-4 py-3 text-sm text-slate-600 dark:border-zinc-700 dark:bg-zinc-800/50 dark:text-zinc-300">
                Select a member above to enter due and payment details.
              </p>
            )}

            {showDetails && historyOnlyMember && (
              <div className="rounded-lg border border-emerald-200 bg-emerald-50 px-4 py-3 text-base text-emerald-900 dark:border-emerald-800 dark:bg-emerald-950/30 dark:text-emerald-100">
                <strong>
                  {selectedMember?.status === 'Separated' ? 'Married Away' : 'Deceased'}
                </strong>
                : paid dues stay on this list. Their entries show below — you cannot add new dues for
                them.
              </div>
            )}

            {showDetails && !historyOnlyMember && (
              <>
                {membershipEligibleBlocked && (
                  <div className="rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 text-base text-amber-900">
                    Membership due is only for members <strong>aged 18+</strong> with date of birth on
                    file. Choose <strong>Harvest</strong> or <strong>Cemetery</strong> for younger
                    members.
                  </div>
                )}

                {isSubscription && personId && selectedMember && (
                  <div className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-emerald-200 bg-emerald-50 px-4 py-3 text-base text-emerald-900">
                    <p>
                      {membershipStatus?.paidUntilLabel ? (
                        <>
                          Already paid until <strong>{membershipStatus.paidUntilLabel}</strong>.
                        </>
                      ) : (
                        <>No membership payments yet for this member.</>
                      )}
                    </p>
                    <button
                      type="button"
                      className={`${ui.btnOutline} inline-flex items-center gap-2 bg-white`}
                      onClick={() => setHistoryOpen(true)}
                    >
                      <History className="h-4 w-4" aria-hidden />
                      Payment history
                    </button>
                  </div>
                )}

                {isSubscription && !loadingMembershipStatus && monthlyRate > 0 && (
                  <MembershipPaymentGuide
                    paidUntilLabel={membershipStatus?.paidUntilLabel ?? null}
                    choices={(() => {
                      const list: MembershipPayChoice[] = [];
                      const finishNext = Number(membershipStatus?.nextDueMonth?.remaining);
                      const nextLabel = membershipStatus?.nextDueMonth?.label;
                      const three = membershipAmountForMonths(
                        monthlyRate,
                        3,
                        Number.isFinite(finishNext) &&
                          finishNext > 0 &&
                          finishNext < monthlyRate
                          ? finishNext
                          : undefined
                      );
                      if (three > 0) {
                        list.push({
                          id: 'three-months',
                          title: 'Pay for 3 months',
                          subtitle: 'Minimum suggested collection',
                          amount: three,
                          primary: true,
                        });
                      }
                      if (
                        Number.isFinite(finishNext) &&
                        finishNext > 0 &&
                        finishNext < monthlyRate &&
                        nextLabel
                      ) {
                        list.push({
                          id: 'finish-month',
                          title: 'Finish this month',
                          subtitle: `Complete ${nextLabel}`,
                          amount: finishNext,
                        });
                      }
                      list.push({
                        id: 'one-month',
                        title: 'Pay for 1 month',
                        subtitle: 'Usual amount to collect',
                        amount: roundPayUnit,
                      });
                      const toCurrent = Math.round(
                        Number(membershipStatus?.toCurrentMonthAmount) || 0
                      );
                      if (toCurrent > three) {
                        const now = new Date();
                        const curLabel = now.toLocaleString('en-IN', {
                          month: 'short',
                          year: 'numeric',
                        });
                        list.push({
                          id: 'to-current',
                          title: 'Catch up to this month',
                          subtitle: `First unpaid → ${curLabel} (incl. last year if due)`,
                          amount: toCurrent,
                        });
                      }
                      const yearAmt = Number(membershipStatus?.completeYearAmount);
                      if (Number.isFinite(yearAmt) && yearAmt > roundPayUnit) {
                        list.push({
                          id: 'finish-year',
                          title: `Finish ${year}`,
                          subtitle: `Through December ${year}`,
                          amount: yearAmt,
                        });
                      }
                      return list;
                    })()}
                    selectedAmount={Number(amountDue) || 0}
                    coverage={membershipCoverage}
                    summary={membershipPaymentPlainSummary(Number(amountDue) || 0, monthlyRate, {
                      completeYearAmount: membershipStatus?.completeYearAmount,
                      completeYearLabel: String(year),
                      finishMonthAmount:
                        Number(membershipStatus?.nextDueMonth?.remaining) > 0 &&
                        Number(membershipStatus?.nextDueMonth?.remaining) < monthlyRate
                          ? Number(membershipStatus?.nextDueMonth?.remaining)
                          : null,
                      finishMonthLabel: membershipStatus?.nextDueMonth?.label,
                      coverageUntil: membershipCoverage?.paidUntilLabel,
                    })}
                    onPick={(amount) => {
                      setAmountDue(String(amount));
                      setAmountPaid('');
                      if (!paidDate) {
                        setPaidDate(new Date().toISOString().slice(0, 10));
                      }
                    }}
                  />
                )}

                {isSubscription &&
                  (membershipStatus?.paymentHistory?.length ?? 0) > 0 && (
                  <div className="rounded-lg border border-slate-200 bg-white px-4 py-3 text-sm dark:border-zinc-700 dark:bg-zinc-900">
                    <p className="mb-2 font-semibold text-slate-800 dark:text-zinc-100">
                      Recent payments
                    </p>
                    <ul className="space-y-1 text-xs text-slate-600 dark:text-zinc-300">
                      {membershipStatus!.paymentHistory!.slice(0, 5).map((p) => (
                        <li key={p.id}>
                          ₹{new Intl.NumberFormat('en-IN').format(p.amount)}
                          {p.paidDate
                            ? ` · ${new Date(p.paidDate).toLocaleDateString('en-IN')}`
                            : ''}
                          {p.paidUntil?.label ? ` · paid until ${p.paidUntil.label}` : ''}
                        </li>
                      ))}
                    </ul>
                  </div>
                )}

                <div className="grid gap-6 sm:grid-cols-2">
                  <label className="block">
                    <span className={labelClass}>Due type *</span>
                    <select
                      value={dueTypeId}
                      onChange={(e) => {
                        setDueTypeId(e.target.value);
                        setSuccessNote('');
                      }}
                      className={inputClass}
                      required
                    >
                      {dueTypes.map((dt) => (
                        <option key={dt.id} value={dt.id}>
                          {dueTypeDisplayName(dt)}
                        </option>
                      ))}
                    </select>
                  </label>

                  <label className="block">
                    <span className={labelClass}>Year this due belongs to *</span>
                    <AmountNumberInput
                      min={FEES_SYSTEM_START_YEAR}
                      max={2100}
                      required
                      inputMode="numeric"
                      value={year}
                      onChange={(e) => {
                        const nextYear = Number(e.target.value);
                        setYear(nextYear);
                        setSuccessNote('');
                        if (Number.isFinite(nextYear) && nextYear >= FEES_SYSTEM_START_YEAR) {
                          onYearChange?.(nextYear);
                        }
                      }}
                      className={inputClass}
                    />
                    <p className="mt-1 text-xs text-slate-500">
                      From {FEES_SYSTEM_START_YEAR} onward only. For earlier balances, use Previous
                      dues on the member profile.
                    </p>
                  </label>

                  <label className="block">
                    <span className={labelClass}>Assigned on *</span>
                    <DatePartsField
                      value={assignedDate}
                      onChange={(v) => {
                        setAssignedDate(v);
                        setSuccessNote('');
                      }}
                      required
                      selectClassName={inputClass}
                      aria-label="Date this due was assigned"
                      disableFuture
                    />
                    <p className="mt-1 text-xs text-slate-500">
                      The day you assign this due (you can assign several types on the same day).
                    </p>
                  </label>

                  {selectedType?.frequency === 'MONTHLY' && (
                    <label className="block">
                      <span className={labelClass}>Month *</span>
                      <select
                        value={month}
                        onChange={(e) => setMonth(e.target.value)}
                        className={inputClass}
                        required
                      >
                        <option value="">Select month</option>
                        {Array.from({ length: 12 }, (_, i) => i + 1).map((m) => (
                          <option key={m} value={m}>
                            {new Date(2000, m - 1, 1).toLocaleString('en-IN', { month: 'long' })}
                          </option>
                        ))}
                      </select>
                    </label>
                  )}

                  <label className="block sm:col-span-2">
                    <span className={labelClass}>
                      {isSubscription ? 'Or type amount (₹) *' : 'Amount due (₹) *'}
                    </span>
                    <AmountNumberInput
                      min={0}
                      step={1}
                      required
                      value={amountDue}
                      onChange={(e) => {
                        const next = e.target.value;
                        setAmountDue(next);
                        setSuccessNote('');
                        if (
                          !isSubscription &&
                          paymentMode === 'record' &&
                          (amountPaid === '' ||
                            Number(amountPaid) === 0 ||
                            Number(amountPaid) === Number(amountDue))
                        ) {
                          const n = Number(next);
                          if (Number.isFinite(n) && n > 0) {
                            setAmountPaid(String(Math.round(n)));
                          }
                        }
                      }}
                      className={`${inputClass}${
                        amountDue.trim() !== '' && Number(amountDue) > 0
                          ? ' border-sky-400 ring-2 ring-sky-200 focus:border-sky-500 dark:border-sky-600 dark:ring-sky-900'
                          : ''
                      }`}
                      placeholder={
                        isSubscription ? 'Membership rate' : 'Enter amount for this person'
                      }
                    />
                    {isSubscription && (selectedType?.defaultAmount ?? 0) > 0 && (
                      <p className="mt-2 text-sm text-slate-500">
                        Membership rate: ₹
                        {new Intl.NumberFormat('en-IN').format(selectedType!.defaultAmount)}
                        {personId && remaining != null && remaining !== selectedType!.defaultAmount
                          ? ` · Remaining for this member: ₹${new Intl.NumberFormat('en-IN').format(remaining)}`
                          : ''}
                      </p>
                    )}
                    {!isSubscription && (
                      <p className="mt-2 text-sm text-slate-500">
                        Enter the amount for this person (no shared default).
                      </p>
                    )}
                    {amountCheck.warnings.length > 0 && (
                      <p className="mt-2 rounded-lg border border-amber-200 bg-amber-50 px-3 py-2 text-sm text-amber-900">
                        {amountCheck.warnings[0]}
                      </p>
                    )}
                  </label>

                  {isSubscription ? (
                    <>
                      <label className="block">
                        <span className={labelClass}>Paid amount (₹)</span>
                        <AmountNumberInput
                          min={0}
                          step={1}
                          value={amountPaid}
                          onChange={(e) => setAmountPaid(e.target.value)}
                          className={inputClass}
                          placeholder="0 if unpaid"
                        />
                      </label>

                      <label className="block">
                        <span className={labelClass}>
                          Payment date{Number(amountPaid) > 0 ? ' *' : ''}
                        </span>
                        <DatePartsField
                          value={paidDate}
                          onChange={setPaidDate}
                          required={Number(amountPaid) > 0}
                          selectClassName={inputClass}
                          aria-label="Payment date"
                          disableFuture
                        />
                        <p className="mt-1 text-xs text-slate-500">
                          Payment date cannot be in the future.
                        </p>
                      </label>
                    </>
                  ) : null}
                </div>

                {!isSubscription ? (
                  <AssignDuePaymentSection
                    mode={paymentMode}
                    onModeChange={setPaymentMode}
                    amountDue={amountDue}
                    amountPaid={amountPaid}
                    onAmountPaidChange={setAmountPaid}
                    paidDate={paidDate}
                    onPaidDateChange={setPaidDate}
                    labelClass={labelClass}
                    inputClass={inputClass}
                  />
                ) : null}

                <label className="block">
                  <span className={labelClass}>Comments</span>
                  <textarea
                    rows={3}
                    value={comments}
                    onChange={(e) => setComments(e.target.value)}
                    className={`${ui.input} mt-2 w-full resize-y text-lg leading-relaxed`}
                    placeholder="Optional notes"
                  />
                </label>
              </>
            )}
          </div>
        )}

        {showDetails && !historyOnlyMember && (
          <div
            className={
              inModal
                ? 'sticky bottom-0 z-10 -mx-6 mt-5 flex flex-wrap justify-end gap-4 border-t border-slate-200 bg-white px-6 py-4 dark:border-zinc-700 dark:bg-zinc-900 sm:-mx-10 sm:px-10'
                : 'flex flex-wrap justify-end gap-4 border-t border-slate-100 pt-5 dark:border-zinc-800'
            }
          >
            {onCancel && (
              <button
                type="button"
                onClick={onCancel}
                className={`${ui.btnOutline} px-6 py-3 text-base`}
              >
                Cancel
              </button>
            )}
            <button
              type="submit"
              disabled={saving || dueTypes.length === 0 || !personId || membershipBlocked}
              className={`${ui.btnPrimary} px-6 py-3 text-base`}
            >
              {saving ? 'Saving…' : 'Add due'}
            </button>
          </div>
        )}
      </form>

      <ConfirmDueAmountDialog
        open={confirmOpen}
        mode="add"
        title="Confirm due entry"
        amount={Number(amountDue) || 0}
        expectedAmount={expectedAmount}
        confirmLabel={saving ? 'Saving…' : 'Yes, save entry'}
        rows={[
          { label: 'Member', value: selectedMember?.fullName || '—' },
          { label: 'Due type', value: dueTypeDisplayName(selectedType) || '—' },
          { label: 'Year', value: String(year) },
          ...(assignedDate.trim()
            ? [{ label: 'Assigned on', value: assignedDate.trim() }]
            : []),
          ...(monthLabel ? [{ label: 'Month', value: monthLabel }] : []),
          {
            label: 'Payment',
            value:
              !isSubscription && paymentMode === 'unpaid'
                ? 'Unpaid'
                : `Paid ₹${new Intl.NumberFormat('en-IN').format(Number(amountPaid) || 0)}`,
          },
          ...(paidDate &&
          (isSubscription || paymentMode === 'record' || Number(amountPaid) > 0)
            ? [{ label: 'Payment date', value: paidDate }]
            : []),
          ...(comments.trim() ? [{ label: 'Comments', value: comments.trim() }] : []),
        ]}
        onCancel={() => !saving && setConfirmOpen(false)}
        onConfirm={() => {
          if (!saving) void saveDue();
        }}
      />

      {personId && selectedMember ? (
        <MembershipPaymentHistoryModal
          open={historyOpen}
          personId={personId}
          memberName={selectedMember.fullName}
          onClose={() => setHistoryOpen(false)}
        />
      ) : null}
    </div>
  );
}
