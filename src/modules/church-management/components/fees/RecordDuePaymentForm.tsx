import { useEffect, useMemo, useState } from 'react';
import { History } from 'lucide-react';
import type { MemberDue } from '@/modules/church-management/api/fees';
import { feesApi } from '@/modules/church-management/api/fees';
import { ui } from '@/modules/church-management/components/family-detail/familyDetailTheme';
import { ConfirmDueAmountDialog } from '@/modules/church-management/components/fees/ConfirmDueAmountDialog';
import { PaymentAmountHint } from '@/modules/church-management/components/fees/PaymentAmountHint';
import {
  MembershipPaymentGuide,
  membershipPaymentPlainSummary,
  type MembershipPayChoice,
} from '@/modules/church-management/components/fees/MembershipPaymentGuide';
import { MembershipPayStatusStrip } from '@/modules/church-management/components/fees/MembershipPayStatusStrip';
import { MembershipFifoNotice } from '@/modules/church-management/components/fees/MembershipFifoNotice';
import { MembershipPaymentHistoryModal } from '@/modules/church-management/components/fees/MembershipPaymentHistoryModal';
import {
  checkPaymentAmount,
  checkWholeMonthPayment,
  formatRupee,
  membershipCompleteYearAmount,
  membershipMonthlyRate,
  membershipRoundPayUnit,
} from '@/modules/church-management/lib/dueAmountValidation';
import {
  membershipAmountForMonths,
  previewMembershipCoverage,
} from '@/modules/church-management/lib/membershipCoverage';
import { isAutoGenerateDueType } from '@/modules/church-management/lib/dueTypes';
import { DatePartsField } from '@/components/DatePartsField';
import { AmountNumberInput } from '@/modules/church-management/components/fees/AmountNumberInput';

function monthLabel(year: number, month: number): string {
  return new Date(year, month - 1, 1).toLocaleString('en-IN', {
    month: 'short',
    year: 'numeric',
  });
}

export function RecordDuePaymentForm({
  due,
  prefillAmount,
  prefillChoice,
  onCancel,
  onSaved,
}: {
  due: MemberDue;
  prefillAmount?: number;
  prefillChoice?: string;
  onCancel: () => void;
  onSaved: () => void;
}) {
  const [amountPaying, setAmountPaying] = useState('');
  const [paidDate, setPaidDate] = useState('');
  const [comments, setComments] = useState('');
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState('');
  const [confirmOpen, setConfirmOpen] = useState(false);
  const [historyOpen, setHistoryOpen] = useState(false);
  const [showTimeline, setShowTimeline] = useState(false);
  const [yearRates, setYearRates] = useState<Record<number, number> | null>(null);
  const [fallbackAnnual, setFallbackAnnual] = useState(0);
  const [billStart, setBillStart] = useState<{
    year: number;
    month: number;
    remaining?: number;
    label?: string;
  } | null>(null);
  const [toCurrentAmount, setToCurrentAmount] = useState(0);
  const [paidUntilLabel, setPaidUntilLabel] = useState<string | null>(null);

  const isMembership = !!due?.dueType && isAutoGenerateDueType(due.dueType);
  const monthlyRate = useMemo(() => {
    if (!due || !isMembership) return 0;
    const annual = fallbackAnnual || Number(due.dueType?.defaultAmount) || 0;
    const fromAnnual = membershipMonthlyRate(annual);
    if (fromAnnual > 0) return fromAnnual;
    const rowDue = Math.round(Number(due.amountDue) || 0);
    return rowDue > 0 ? rowDue : 0;
  }, [due, isMembership, fallbackAnnual]);

  useEffect(() => {
    if (!due || !isMembership) {
      setYearRates(null);
      setBillStart(null);
      setToCurrentAmount(0);
      setPaidUntilLabel(null);
      return;
    }
    let cancelled = false;
    void (async () => {
      const res = await feesApi.getPersonFeeStatus(due.personId, due.year);
      if (cancelled || !res.data) return;
      setYearRates(res.data.yearRates ?? null);
      setFallbackAnnual(
        Number(res.data.annualRate) || Number(due.dueType?.defaultAmount) || 0
      );
      setToCurrentAmount(Math.round(Number(res.data.toCurrentMonthAmount) || 0));
      setPaidUntilLabel(res.data.paidUntilLabel ?? res.data.paidUntil?.label ?? null);
      const next = res.data.nextDueMonth;
      if (next?.year && next?.month) {
        setBillStart({
          year: next.year,
          month: next.month,
          remaining: next.remaining,
          label: next.label,
        });
      } else {
        setBillStart({ year: due.year, month: 1 });
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [due, isMembership]);

  const roundPayUnit = useMemo(
    () => membershipRoundPayUnit(monthlyRate),
    [monthlyRate]
  );

  const billYear = billStart?.year ?? due?.year ?? new Date().getFullYear();
  const billMonth = billStart?.month ?? 1;
  const monthRemaining = useMemo(() => {
    if (!due || !isMembership) return 0;
    if (billStart?.remaining != null && billStart.remaining > 0) {
      return Math.round(billStart.remaining);
    }
    return Math.max(0, Math.round(due.amountDue - due.amountPaid));
  }, [due, isMembership, billStart]);

  const finishMonthLabel =
    billStart?.label || (billMonth >= 1 ? monthLabel(billYear, billMonth) : null);

  const openedMonth = Number(due?.month) || 0;
  const openedYear = Number(due?.year) || 0;
  const openedLabel =
    openedMonth >= 1 && openedMonth <= 12 && openedYear > 0
      ? monthLabel(openedYear, openedMonth)
      : due
        ? String(due.year)
        : '';
  const paymentStartsElsewhere =
    isMembership &&
    billStart != null &&
    openedMonth >= 1 &&
    (openedYear !== billYear || openedMonth !== billMonth);

  const completeYear = useMemo(() => {
    if (!due || !isMembership || monthlyRate < 1) return null;
    return membershipCompleteYearAmount(
      monthlyRate,
      billYear,
      billMonth,
      due.year,
      monthRemaining > 0 && monthRemaining < monthlyRate ? monthRemaining : undefined
    );
  }, [due, isMembership, monthlyRate, billYear, billMonth, monthRemaining]);

  const threeMonthsAmount = useMemo(
    () =>
      membershipAmountForMonths(
        monthlyRate,
        3,
        monthRemaining > 0 && monthRemaining < monthlyRate ? monthRemaining : undefined
      ),
    [monthlyRate, monthRemaining]
  );

  const choices = useMemo((): MembershipPayChoice[] => {
    if (!due || !isMembership || monthlyRate < 1) return [];
    const list: MembershipPayChoice[] = [];
    if (threeMonthsAmount > 0) {
      list.push({
        id: 'three-months',
        title: 'Pay for 3 months',
        subtitle: 'Minimum suggested',
        amount: threeMonthsAmount,
        primary: true,
      });
    }
    if (monthRemaining > 0 && monthRemaining < monthlyRate && finishMonthLabel) {
      list.push({
        id: 'finish-month',
        title: 'Finish this month',
        subtitle: finishMonthLabel,
        amount: monthRemaining,
      });
    }
    list.push({
      id: 'one-month',
      title: 'Pay for 1 month',
      subtitle: 'Usual amount',
      amount: roundPayUnit,
    });
    if (toCurrentAmount > threeMonthsAmount) {
      const now = new Date();
      list.push({
        id: 'to-current',
        title: 'Catch up to this month',
        subtitle: monthLabel(now.getFullYear(), now.getMonth() + 1),
        amount: toCurrentAmount,
      });
    }
    if (completeYear && completeYear.amount > roundPayUnit) {
      list.push({
        id: 'finish-year',
        title: `Finish ${due.year}`,
        subtitle: `Through December ${due.year}`,
        amount: completeYear.amount,
      });
    }
    return list;
  }, [
    due,
    isMembership,
    monthlyRate,
    monthRemaining,
    finishMonthLabel,
    roundPayUnit,
    completeYear,
    threeMonthsAmount,
    toCurrentAmount,
  ]);

  useEffect(() => {
    if (!due) return;
    if (isMembership && monthlyRate > 0) {
      if (prefillAmount != null && prefillAmount > 0) {
        setAmountPaying(String(Math.round(prefillAmount)));
      } else {
        const preferred =
          monthRemaining > 0 && monthRemaining < monthlyRate
            ? monthRemaining
            : threeMonthsAmount > 0
              ? threeMonthsAmount
              : roundPayUnit;
        setAmountPaying(String(preferred));
      }
    } else {
      const remaining = Math.max(0, due.amountDue - due.amountPaid);
      setAmountPaying(String(remaining > 0 ? remaining : ''));
    }
    setPaidDate(new Date().toISOString().slice(0, 10));
    setComments(due.comments || '');
    setError('');
    setConfirmOpen(false);
    setShowTimeline(false);
  }, [
    due,
    isMembership,
    monthlyRate,
    roundPayUnit,
    monthRemaining,
    threeMonthsAmount,
    prefillAmount,
    prefillChoice,
  ]);

  const payingAmt = Number(amountPaying) || 0;
  const paymentCheck = useMemo(() => {
    if (!due) return checkPaymentAmount(0, 0, 0);
    if (isMembership && monthlyRate > 0) {
      return checkWholeMonthPayment(payingAmt, monthlyRate);
    }
    return checkPaymentAmount(payingAmt, due.amountDue, due.amountPaid);
  }, [due, payingAmt, isMembership, monthlyRate]);

  const coverage = useMemo(() => {
    if (!due || !isMembership || monthlyRate < 1) return null;
    const annual =
      fallbackAnnual || Number(due.dueType?.defaultAmount) || monthlyRate * 12;
    return previewMembershipCoverage({
      amountPaid: payingAmt,
      startYear: billYear,
      startMonth: billMonth,
      startMonthRemaining:
        monthRemaining > 0 && monthRemaining < monthlyRate ? monthRemaining : undefined,
      fallbackAnnual: annual,
      yearRates,
    });
  }, [
    due,
    isMembership,
    monthlyRate,
    payingAmt,
    monthRemaining,
    fallbackAnnual,
    yearRates,
    billYear,
    billMonth,
  ]);

  const plainSummary = useMemo(() => {
    if (!isMembership || monthlyRate < 1 || payingAmt < 1) return '';
    return membershipPaymentPlainSummary(payingAmt, monthlyRate, {
      completeYearAmount: completeYear?.amount,
      completeYearLabel: due ? String(due.year) : null,
      finishMonthAmount:
        monthRemaining > 0 && monthRemaining < monthlyRate ? monthRemaining : null,
      finishMonthLabel,
      coverageUntil: coverage?.paidUntilLabel,
    });
  }, [
    isMembership,
    monthlyRate,
    payingAmt,
    completeYear,
    due,
    monthRemaining,
    finishMonthLabel,
    coverage?.paidUntilLabel,
  ]);

  const savePayment = async () => {
    if (!due) return;
    try {
      setSaving(true);
      setError('');
      const amountPaid = isMembership ? payingAmt : due.amountPaid + payingAmt;
      const res = await feesApi.recordPayment(due.id, {
        amountPaid,
        paidDate: paidDate || undefined,
        comments: comments.trim() || undefined,
      });
      if (res.error) {
        setError(res.error);
        setConfirmOpen(false);
        return;
      }
      setConfirmOpen(false);
      onSaved();
    } catch {
      setError('Could not record payment');
      setConfirmOpen(false);
    } finally {
      setSaving(false);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (payingAmt <= 0 || amountPaying === '') {
      setError('Enter a valid paying amount');
      return;
    }
    if (isMembership && paymentCheck.needsReentry) {
      setError(paymentCheck.warnings[0] || 'Enter a valid membership amount');
      return;
    }
    setError('');
    setConfirmOpen(true);
  };

  const personName = due.personName || due.person?.fullName || '—';

  return (
    <>
      <form onSubmit={handleSubmit} className="mx-auto w-full max-w-5xl space-y-6">
        {error && (
          <div className="rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
            {error}
          </div>
        )}

        {isMembership ? (
          <>
            <MembershipPayStatusStrip
              paidUntilLabel={paidUntilLabel}
              nextDueLabel={finishMonthLabel}
              monthlyRate={monthlyRate}
              toCurrentAmount={toCurrentAmount}
            />
            {billStart && finishMonthLabel ? (
              <MembershipFifoNotice
                openedLabel={openedLabel || finishMonthLabel}
                appliesFromLabel={finishMonthLabel}
                mismatch={paymentStartsElsewhere}
              />
            ) : null}
            <div className="flex justify-end">
              <button
                type="button"
                className={`${ui.btnOutline} inline-flex items-center gap-2`}
                onClick={() => setHistoryOpen(true)}
              >
                <History className="h-4 w-4" aria-hidden />
                Payment history
              </button>
            </div>

            <div>
              <label
                htmlFor="payment-amount"
                className="mb-2 block text-sm font-semibold text-slate-700 dark:text-zinc-300"
              >
                Amount collecting (₹)
              </label>
              <AmountNumberInput
                id="payment-amount"
                min={0}
                step={1}
                required
                value={amountPaying}
                onChange={(e) => setAmountPaying(e.target.value)}
                className={`${ui.select} w-full max-w-md text-2xl font-semibold ${
                  paymentCheck.needsReentry ? 'border-red-400' : ''
                }`}
              />
              {payingAmt > 0 && plainSummary ? (
                <p className="mt-2 max-w-2xl rounded-lg border border-emerald-200 bg-emerald-50 px-4 py-3 text-base font-medium text-emerald-950 dark:border-emerald-800 dark:bg-emerald-950/40 dark:text-emerald-100">
                  {plainSummary}
                  {coverage?.paidUntilLabel ? ` → until ${coverage.paidUntilLabel}` : ''}
                </p>
              ) : null}
              {paymentCheck.needsReentry ? (
                <PaymentAmountHint
                  level={paymentCheck.level}
                  messages={paymentCheck.warnings}
                />
              ) : null}
            </div>

            <MembershipPaymentGuide
              choices={choices}
              selectedAmount={payingAmt}
              summary=""
              paidUntilLabel={null}
              coverage={coverage}
              showTimeline={showTimeline}
              onToggleTimeline={() => setShowTimeline((v) => !v)}
              onPick={(amount) => setAmountPaying(String(amount))}
            />
          </>
        ) : (
          <>
            <div className="rounded-lg border border-slate-200 bg-slate-50 px-4 py-3 text-sm text-slate-700">
              <p>
                <span className="font-semibold">Amount due:</span> {formatRupee(due.amountDue)}
              </p>
              <p className="mt-1">
                <span className="font-semibold">Already paid:</span> {formatRupee(due.amountPaid)}
              </p>
              <p className="mt-1">
                <span className="font-semibold">Remaining:</span>{' '}
                {formatRupee(paymentCheck.remaining)}
              </p>
            </div>
            <div>
              <label
                htmlFor="payment-amount"
                className="mb-2 block text-sm font-semibold text-slate-700"
              >
                Amount paying (₹)
              </label>
              <AmountNumberInput
                id="payment-amount"
                min={0}
                step={1}
                required
                value={amountPaying}
                onChange={(e) => setAmountPaying(e.target.value)}
                className={`${ui.select} w-full max-w-md text-2xl font-semibold`}
              />
              <PaymentAmountHint
                level={paymentCheck.level}
                messages={paymentCheck.warnings}
                remainingLabel={`Remaining ${formatRupee(paymentCheck.remaining)}`}
              />
            </div>
          </>
        )}

        <div className="grid gap-4 sm:grid-cols-2">
          <div>
            <span className="mb-2 block text-sm font-semibold text-slate-700 dark:text-zinc-300">
              Payment date
            </span>
            <DatePartsField
              value={paidDate}
              onChange={setPaidDate}
              selectClassName={`${ui.select} w-full py-2.5`}
              aria-label="Payment date"
              disableFuture
            />
          </div>
          <div>
            <label
              htmlFor="payment-comments"
              className="mb-2 block text-sm font-semibold text-slate-700 dark:text-zinc-300"
            >
              Notes (optional)
            </label>
            <textarea
              id="payment-comments"
              rows={2}
              value={comments}
              onChange={(e) => setComments(e.target.value)}
              className={`${ui.select} w-full`}
              placeholder="Receipt no., remarks…"
            />
          </div>
        </div>

        <div className="sticky bottom-0 z-10 flex flex-wrap justify-end gap-3 border-t border-slate-200 bg-white/95 py-4 backdrop-blur dark:border-zinc-700 dark:bg-zinc-950/95">
          <button type="button" onClick={onCancel} className={ui.btnOutline}>
            Cancel
          </button>
          <button type="submit" disabled={saving} className={ui.btnPrimary}>
            {saving ? 'Saving…' : 'Save payment'}
          </button>
        </div>
      </form>

      <MembershipPaymentHistoryModal
        open={historyOpen}
        personId={due.personId}
        memberName={personName}
        onClose={() => setHistoryOpen(false)}
      />

      <ConfirmDueAmountDialog
        open={confirmOpen}
        mode="payment"
        title="Confirm payment"
        amount={payingAmt}
        amountDue={isMembership ? monthlyRate : due.amountDue}
        alreadyPaid={isMembership ? 0 : due.amountPaid}
        membershipMonthlyRate={isMembership && monthlyRate > 0 ? monthlyRate : null}
        confirmLabel={saving ? 'Saving…' : 'Yes, save'}
        rows={[
          { label: 'Member', value: personName },
          { label: 'Collecting', value: formatRupee(payingAmt) },
          ...(isMembership && finishMonthLabel
            ? [
                {
                  label: 'Applies from',
                  value: paymentStartsElsewhere
                    ? `${finishMonthLabel} (oldest unpaid — not ${openedLabel})`
                    : finishMonthLabel,
                },
              ]
            : []),
          ...(isMembership && plainSummary
            ? [{ label: 'Result', value: plainSummary }]
            : [
                { label: 'Due', value: formatRupee(due.amountDue) },
                { label: 'Already paid', value: formatRupee(due.amountPaid) },
              ]),
        ]}
        notice={
          isMembership && paymentStartsElsewhere && finishMonthLabel
            ? `Opened ${openedLabel}, but payment clears ${finishMonthLabel} first, then later months in order.`
            : isMembership
              ? 'Membership payments always clear the oldest unpaid month first; leftover rolls forward.'
              : undefined
        }
        onCancel={() => !saving && setConfirmOpen(false)}
        onConfirm={() => {
          if (!saving) void savePayment();
        }}
      />
    </>
  );
}
